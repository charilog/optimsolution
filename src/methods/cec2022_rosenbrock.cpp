void CEC2022Rosenbrock::init(int dim)
{
    if (!(dim == 2 || dim == 10 || dim == 20)) {
        throw std::invalid_argument("CEC2022Rosenbrock supports only D = 2, 10, or 20.");
    }

    Problem::init(dim);

    Vec lo(dim, -100.0), hi(dim, 100.0);
    setBounds(lo, hi);

    load_embedded_data(dim);
}

void CEC2022Rosenbrock::load_embedded_data(int dim)
{
    const double* shift_ptr = shift_data_for_dim(dim);
    const double* rot_ptr   = rotation_data_for_dim(dim);

    if (!shift_ptr || !rot_ptr) {
        throw std::runtime_error("Embedded CEC2022Rosenbrock data are unavailable for the requested dimension.");
    }

    shift_.assign(shift_ptr, shift_ptr + dim);
    rotation_.assign(rot_ptr, rot_ptr + dim * dim);
}

double CEC2022Rosenbrock::evaluate_core(const Vec& x)
{
    const int D = dimension();
    const double scale = 2.048 / 100.0;

    Vec z(D, 0.0);
    for (int i = 0; i < D; ++i) {
        double acc = 0.0;
        for (int j = 0; j < D; ++j) {
            acc += rotation_[i * D + j] * (scale * (x[j] - shift_[j]));
        }
        z[i] = acc + 1.0;
    }

    double f = 0.0;
    for (int i = 0; i < D - 1; ++i) {
        const double t1 = z[i] * z[i] - z[i + 1];
        const double t2 = z[i] - 1.0;
        f += 100.0 * t1 * t1 + t2 * t2;
    }

    return f + 400.0;
}

void CEC2022Rosenbrock::gradient_core(const Vec& x, Vec& g)
{
    const int D = dimension();
    const double scale = 2.048 / 100.0;

    Vec z(D, 0.0);
    for (int i = 0; i < D; ++i) {
        double acc = 0.0;
        for (int j = 0; j < D; ++j) {
            acc += rotation_[i * D + j] * (scale * (x[j] - shift_[j]));
        }
        z[i] = acc + 1.0;
    }

    Vec grad_z(D, 0.0);
    if (D >= 2) {
        grad_z[0] = 400.0 * z[0] * (z[0] * z[0] - z[1]) + 2.0 * (z[0] - 1.0);
        for (int i = 1; i < D - 1; ++i) {
            grad_z[i] = -200.0 * (z[i - 1] * z[i - 1] - z[i])
                      + 400.0 * z[i] * (z[i] * z[i] - z[i + 1])
                      + 2.0 * (z[i] - 1.0);
        }
        grad_z[D - 1] = -200.0 * (z[D - 2] * z[D - 2] - z[D - 1]);
    }

    g.assign(D, 0.0);
    for (int j = 0; j < D; ++j) {
        double acc = 0.0;
        for (int i = 0; i < D; ++i) {
            acc += rotation_[i * D + j] * grad_z[i];
        }
        g[j] = scale * acc;
    }
}

