void CEC2022Zakharov::init(int dim)
{
    if (!(dim == 2 || dim == 10 || dim == 20)) {
        throw std::invalid_argument("CEC2022Zakharov supports only D = 2, 10, or 20.");
    }

    Problem::init(dim);

    Vec lo(dim, -100.0), hi(dim, 100.0);
    setBounds(lo, hi);

    load_embedded_data(dim);
}

void CEC2022Zakharov::load_embedded_data(int dim)
{
    const double* shift_ptr = shift_data_for_dim(dim);
    const double* rot_ptr   = rotation_data_for_dim(dim);

    if (!shift_ptr || !rot_ptr) {
        throw std::runtime_error("Embedded CEC2022Zakharov data are unavailable for the requested dimension.");
    }

    shift_.assign(shift_ptr, shift_ptr + dim);
    rotation_.assign(rot_ptr, rot_ptr + dim * dim);
}

double CEC2022Zakharov::evaluate_core(const Vec& x)
{
    const int D = dimension();

    Vec z(D, 0.0);
    for (int i = 0; i < D; ++i) {
        double acc = 0.0;
        for (int j = 0; j < D; ++j) {
            acc += rotation_[i * D + j] * (x[j] - shift_[j]);
        }
        z[i] = acc;
    }

    double sum1 = 0.0;
    double sum2 = 0.0;
    for (int i = 0; i < D; ++i) {
        const double zi = z[i];
        sum1 += zi * zi;
        sum2 += 0.5 * static_cast<double>(i + 1) * zi;
    }

    return sum1 + sum2 * sum2 + sum2 * sum2 * sum2 * sum2 + 300.0;
}

void CEC2022Zakharov::gradient_core(const Vec& x, Vec& g)
{
    const int D = dimension();

    Vec z(D, 0.0);
    for (int i = 0; i < D; ++i) {
        double acc = 0.0;
        for (int j = 0; j < D; ++j) {
            acc += rotation_[i * D + j] * (x[j] - shift_[j]);
        }
        z[i] = acc;
    }

    double s = 0.0;
    for (int i = 0; i < D; ++i) {
        s += 0.5 * static_cast<double>(i + 1) * z[i];
    }

    const double coeff = 2.0 * s + 4.0 * s * s * s;

    Vec grad_z(D, 0.0);
    for (int i = 0; i < D; ++i) {
        grad_z[i] = 2.0 * z[i] + coeff * 0.5 * static_cast<double>(i + 1);
    }

    g.assign(D, 0.0);
    for (int j = 0; j < D; ++j) {
        double acc = 0.0;
        for (int i = 0; i < D; ++i) {
            acc += rotation_[i * D + j] * grad_z[i];
        }
        g[j] = acc;
    }
}

