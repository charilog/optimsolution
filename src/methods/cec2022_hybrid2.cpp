CEC2022Hybrid2::CEC2022Hybrid2()
{
    setName("cec2022hybrid2");
    setFullName("CEC 2022 F6 (reference hf02) - Hybrid Function 2");
    setModality("hybrid");
    setSeparability("non-separable");
    setCategory("CEC 2022 synthetic benchmark");
}

void CEC2022Hybrid2::init(int dim)
{
    if (!(dim == 10 || dim == 20)) {
        throw std::invalid_argument("CEC2022Hybrid2 supports only D = 10 or 20.");
    }

    Problem::init(dim);

    Vec lo(dim, -100.0), hi(dim, 100.0);
    setBounds(lo, hi);

    load_embedded_data(dim);
}

void CEC2022Hybrid2::load_embedded_data(int dim)
{
    const double* shift_ptr = shift_data_for_dim(dim);
    const double* rot_ptr   = rotation_data_for_dim(dim);
    const int* shuf_ptr     = shuffle_data_for_dim(dim);

    if (!shift_ptr || !rot_ptr || !shuf_ptr) {
        throw std::runtime_error("Embedded CEC2022Hybrid2 data are unavailable for the requested dimension.");
    }

    shift_.assign(shift_ptr, shift_ptr + dim);
    rotation_.assign(rot_ptr, rot_ptr + dim * dim);
    shuffle_.assign(shuf_ptr, shuf_ptr + dim);
}

double CEC2022Hybrid2::evaluate_core(const Vec& x)
{
    return hybrid2_value(x, shift_, rotation_, shuffle_);
}

void CEC2022Hybrid2::gradient_core(const Vec& x, Vec& g)
{
    const int D = dimension();
    g.assign(D, 0.0);

    constexpr double eps = 1e-6;
    Vec xp = x, xm = x;
    for (int i = 0; i < D; ++i) {
        const double h = eps * std::max(1.0, std::fabs(x[i]));
        xp[i] = x[i] + h;
        xm[i] = x[i] - h;
        g[i] = (hybrid2_value(xp, shift_, rotation_, shuffle_) - hybrid2_value(xm, shift_, rotation_, shuffle_)) / (2.0 * h);
        xp[i] = x[i];
        xm[i] = x[i];
    }
}

