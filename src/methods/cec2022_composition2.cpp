void CEC2022Composition2::init(int dim) {
    if (!(dim == 2 || dim == 10 || dim == 20)) {
        throw std::invalid_argument("CEC2022Composition2 supports only dimensions 2, 10, and 20");
    }
    Problem::init(dim);
    load_embedded_data(dim);
    Vec lo(dim, -100.0), hi(dim, 100.0);
    setBounds(lo, hi);
}

void CEC2022Composition2::load_embedded_data(int dim) {
    const double* s = shift_data_for_dim(dim);
    const double* r = rotation_data_for_dim(dim);
    if (!s || !r) {
        throw std::runtime_error("Embedded data for CEC2022Composition2 are unavailable for the requested dimension");
    }
    shift_.assign(s, s + 3 * dim);
    rotation_.assign(r, r + 3 * dim * dim);
}

double CEC2022Composition2::evaluate_core(const Vec& x) {
    const int D = dimension();
    if (static_cast<int>(x.size()) != D) {
        throw std::runtime_error("CEC2022Composition2 received a vector with incorrect dimension");
    }

    const double delta[3] = {20.0, 10.0, 10.0};
    const double bias[3]  = {0.0, 200.0, 100.0};
    double fit[3];

    fit[0] = schwefel_func(x, D, &shift_[0 * D], &rotation_[0 * D * D], true, false);
    fit[1] = rastrigin_func(x, D, &shift_[1 * D], &rotation_[1 * D * D], true, true);
    fit[2] = hgbat_func(x, D, &shift_[2 * D], &rotation_[2 * D * D], true, true);

    return cf_cal(x, D, shift_.data(), delta, bias, fit, 3) + 2400.0;
}

void CEC2022Composition2::gradient_core(const Vec& x, Vec& g) {
    const int D = dimension();
    g.assign(D, 0.0);
    if (static_cast<int>(x.size()) != D) return;

    const double h = 1.0e-6;
    Vec xp = x, xm = x;
    for (int i = 0; i < D; ++i) {
        xp[i] += h;
        xm[i] -= h;
        g[i] = (evaluate_core(xp) - evaluate_core(xm)) / (2.0 * h);
        xp[i] = x[i];
        xm[i] = x[i];
    }
}

