CEC2022Levy::CEC2022Levy()
{
    setName("cec2022levy");
    setFullName("CEC 2022 F5 - Shifted and Rotated Levy Function");
    setModality("multimodal");
    setSeparability("non-separable");
    setCategory("CEC 2022 synthetic benchmark");
}

void CEC2022Levy::init(int dim)
{
    if (!(dim == 2 || dim == 10 || dim == 20)) {
        throw std::invalid_argument("CEC2022Levy supports only D = 2, 10, or 20.");
    }

    Problem::init(dim);

    Vec lo(dim, -100.0), hi(dim, 100.0);
    setBounds(lo, hi);

    load_embedded_data(dim);
}

void CEC2022Levy::load_embedded_data(int dim)
{
    const double* shift_ptr = shift_data_for_dim(dim);
    const double* rot_ptr   = rotation_data_for_dim(dim);

    if (!shift_ptr || !rot_ptr) {
        throw std::runtime_error("Embedded CEC2022Levy data are unavailable for the requested dimension.");
    }

    shift_.assign(shift_ptr, shift_ptr + dim);
    rotation_.assign(rot_ptr, rot_ptr + dim * dim);
}

double CEC2022Levy::evaluate_core(const Vec& x)
{
    const int D = dimension();

    Vec z(D, 0.0);
    for (int i = 0; i < D; ++i) {
        double acc = 0.0;
        for (int j = 0; j < D; ++j) {
            acc += rotation_[i * D + j] * (x[j] - shift_[j]);
        }
        z[i] = acc;
    }

    Vec w(D, 0.0);
    for (int i = 0; i < D; ++i) {
        w[i] = 1.0 + 0.25 * z[i];
    }

    const double term1 = std::sin(kPi * w[0]) * std::sin(kPi * w[0]);

    double sum = 0.0;
    for (int i = 0; i < D - 1; ++i) {
        const double wi = w[i];
        const double s = std::sin(kPi * wi + 1.0);
        const double t = wi - 1.0;
        sum += t * t * (1.0 + 10.0 * s * s);
    }

    const double wd = w[D - 1];
    const double s2 = std::sin(2.0 * kPi * wd);
    const double term3 = (wd - 1.0) * (wd - 1.0) * (1.0 + s2 * s2);

    return term1 + sum + term3 + 900.0;
}

void CEC2022Levy::gradient_core(const Vec& x, Vec& g)
{
    const int D = dimension();

    Vec z(D, 0.0);
    for (int i = 0; i < D; ++i) {
        double acc = 0.0;
        for (int j = 0; j < D; ++j) {
            acc += rotation_[i * D + j] * (x[j] - shift_[j]);
        }
        z[i] = acc;
    }

    Vec w(D, 0.0);
    for (int i = 0; i < D; ++i) {
        w[i] = 1.0 + 0.25 * z[i];
    }

    Vec grad_w(D, 0.0);

    // d/dw of sin^2(pi w_1)
    grad_w[0] += kPi * std::sin(2.0 * kPi * w[0]);

    // d/dw of middle sum terms
    for (int i = 0; i < D - 1; ++i) {
        const double wi = w[i];
        const double t = wi - 1.0;
        const double u = kPi * wi + 1.0;
        const double s = std::sin(u);
        const double s2 = s * s;
        grad_w[i] += 2.0 * t * (1.0 + 10.0 * s2)
                   + t * t * (10.0 * kPi * std::sin(2.0 * u));
    }

    // d/dw of final term
    const double wd = w[D - 1];
    const double td = wd - 1.0;
    const double sd = std::sin(2.0 * kPi * wd);
    grad_w[D - 1] += 2.0 * td * (1.0 + sd * sd)
                   + td * td * (2.0 * kPi * std::sin(4.0 * kPi * wd));

    Vec grad_z(D, 0.0);
    for (int i = 0; i < D; ++i) {
        grad_z[i] = 0.25 * grad_w[i];
    }

    g.assign(D, 0.0);
    for (int j = 0; j < D; ++j) {
        double acc = 0.0;
        for (int i = 0; i < D; ++i) {
            acc += rotation_[i * D + j] * grad_z[i];
        }
        g[j] = acc;
    }
}

