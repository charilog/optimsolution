inline void shiftfunc(const Vec& x, Vec& xshift, const double* Os, int nx) {
    xshift.resize(nx);
    for (int i = 0; i < nx; ++i) xshift[i] = x[i] - Os[i];
}

inline void rotatefunc(const Vec& x, Vec& xrot, const double* Mr, int nx) {
    xrot.assign(nx, 0.0);
    for (int i = 0; i < nx; ++i) {
        double acc = 0.0;
        for (int j = 0; j < nx; ++j) acc += x[j] * Mr[i * nx + j];
        xrot[i] = acc;
    }
}

inline void sr_func(const Vec& x, Vec& sr_x, int nx, const double* Os, const double* Mr,
                    double sh_rate, bool s_flag, bool r_flag) {
    Vec y(nx, 0.0);
    if (s_flag) {
        if (r_flag) {
            shiftfunc(x, y, Os, nx);
            for (int i = 0; i < nx; ++i) y[i] *= sh_rate;
            rotatefunc(y, sr_x, Mr, nx);
        } else {
            shiftfunc(x, sr_x, Os, nx);
            for (int i = 0; i < nx; ++i) sr_x[i] *= sh_rate;
        }
    } else {
        if (r_flag) {
            for (int i = 0; i < nx; ++i) y[i] = x[i] * sh_rate;
            rotatefunc(y, sr_x, Mr, nx);
        } else {
            sr_x.resize(nx);
            for (int i = 0; i < nx; ++i) sr_x[i] = x[i] * sh_rate;
        }
    }
}

inline double hgbat_func(const Vec& x, int nx, const double* Os, const double* Mr,
                         bool s_flag, bool r_flag) {
    Vec z;
    sr_func(x, z, nx, Os, Mr, 5.0 / 100.0, s_flag, r_flag);
    double r2 = 0.0;
    double s = 0.0;
    for (int i = 0; i < nx; ++i) {
        z[i] -= 1.0;
        r2 += z[i] * z[i];
        s += z[i];
    }
    return std::sqrt(std::fabs(r2 * r2 - s * s)) + (0.5 * r2 + s) / nx + 0.5;
}

inline double rastrigin_func(const Vec& x, int nx, const double* Os, const double* Mr,
                             bool s_flag, bool r_flag) {
    Vec z;
    sr_func(x, z, nx, Os, Mr, 5.12 / 100.0, s_flag, r_flag);
    double f = 0.0;
    for (int i = 0; i < nx; ++i) {
        f += z[i] * z[i] - 10.0 * std::cos(2.0 * kPi * z[i]) + 10.0;
    }
    return f;
}

inline double schwefel_func(const Vec& x, int nx, const double* Os, const double* Mr,
                            bool s_flag, bool r_flag) {
    Vec z;
    sr_func(x, z, nx, Os, Mr, 1000.0 / 100.0, s_flag, r_flag);
    double f = 0.0;
    for (int i = 0; i < nx; ++i) {
        double zi = z[i] + 4.209687462275036E+002;
        if (zi > 500.0) {
            const double modv = std::fmod(zi, 500.0);
            f -= (500.0 - modv) * std::sin(std::sqrt(500.0 - modv));
            const double tmp = (zi - 500.0) / 100.0;
            f += tmp * tmp / nx;
        } else if (zi < -500.0) {
            const double modv = std::fmod(std::fabs(zi), 500.0);
            f -= (modv - 500.0) * std::sin(std::sqrt(500.0 - modv));
            const double tmp = (zi + 500.0) / 100.0;
            f += tmp * tmp / nx;
        } else {
            f -= zi * std::sin(std::sqrt(std::fabs(zi)));
        }
    }
    f += 4.189828872724338E+002 * nx;
    return f;
}

inline double bent_cigar_func(const Vec& x, int nx, const double* Os, const double* Mr,
                              bool s_flag, bool r_flag) {
    Vec z;
    sr_func(x, z, nx, Os, Mr, 1.0, s_flag, r_flag);
    double f = z[0] * z[0];
    for (int i = 1; i < nx; ++i) f += 1.0E6 * z[i] * z[i];
    return f;
}

inline double ellips_func(const Vec& x, int nx, const double* Os, const double* Mr,
                          bool s_flag, bool r_flag) {
    Vec z;
    sr_func(x, z, nx, Os, Mr, 1.0, s_flag, r_flag);
    double f = 0.0;
    for (int i = 0; i < nx; ++i) {
        f += std::pow(10.0, 6.0 * i / (nx - 1.0)) * z[i] * z[i];
    }
    return f;
}

inline double escaffer6_func(const Vec& x, int nx, const double* Os, const double* Mr,
                             bool s_flag, bool r_flag) {
    Vec z;
    sr_func(x, z, nx, Os, Mr, 1.0, s_flag, r_flag);
    double f = 0.0;
    for (int i = 0; i < nx - 1; ++i) {
        const double sq = z[i] * z[i] + z[i + 1] * z[i + 1];
        double temp1 = std::sin(std::sqrt(sq));
        temp1 *= temp1;
        const double temp2 = 1.0 + 0.001 * sq;
        f += 0.5 + (temp1 - 0.5) / (temp2 * temp2);
    }
    const double sq = z[nx - 1] * z[nx - 1] + z[0] * z[0];
    double temp1 = std::sin(std::sqrt(sq));
    temp1 *= temp1;
    const double temp2 = 1.0 + 0.001 * sq;
    f += 0.5 + (temp1 - 0.5) / (temp2 * temp2);
    return f;
}

inline double cf_cal(const Vec& x, int nx, const double* Os, const double* delta,
                     const double* bias, double* fit, int cf_num) {
    std::vector<double> w(cf_num, 0.0);
    double w_max = 0.0;
    double w_sum = 0.0;

    for (int i = 0; i < cf_num; ++i) {
        fit[i] += bias[i];
        double dist2 = 0.0;
        for (int j = 0; j < nx; ++j) {
            const double d = x[j] - Os[i * nx + j];
            dist2 += d * d;
        }
        if (dist2 != 0.0) {
            w[i] = std::pow(1.0 / dist2, 0.5) *
                   std::exp(-dist2 / (2.0 * nx * delta[i] * delta[i]));
        } else {
            w[i] = kInf;
        }
        if (w[i] > w_max) w_max = w[i];
        w_sum += w[i];
    }

    if (w_max == 0.0) {
        std::fill(w.begin(), w.end(), 1.0);
        w_sum = static_cast<double>(cf_num);
    }

    double f = 0.0;
    for (int i = 0; i < cf_num; ++i) f += (w[i] / w_sum) * fit[i];
    return f;
}


