inline void shiftfunc(const Vec& x, Vec& xshift, const double* Os, int nx) {
    xshift.resize(nx);
    for (int i = 0; i < nx; ++i) xshift[i] = x[i] - Os[i];
}

inline void rotatefunc(const Vec& x, Vec& xrot, const double* Mr, int nx) {
    xrot.assign(nx, 0.0);
    for (int i = 0; i < nx; ++i) {
        double acc = 0.0;
        for (int j = 0; j < nx; ++j) acc += x[j] * Mr[i * nx + j];
        xrot[i] = acc;
    }
}

inline double bent_cigar_sub(const Vec& y, int off, int n) {
    double f = y[off] * y[off];
    for (int i = 1; i < n; ++i) f += 1.0e6 * y[off + i] * y[off + i];
    return f;
}

inline double hgbat_sub(const Vec& y, int off, int n) {
    Vec z(n);
    double r2 = 0.0, sumz = 0.0;
    for (int i = 0; i < n; ++i) {
        const double zi = y[off + i] * (5.0 / 100.0) - 1.0;
        z[i] = zi;
        r2 += zi * zi;
        sumz += zi;
    }
    const double alpha = 0.25;
    return std::pow(std::fabs(r2 * r2 - sumz * sumz), 2.0 * alpha) + (0.5 * r2 + sumz) / double(n) + 0.5;
}

inline double rastrigin_sub(const Vec& y, int off, int n) {
    double f = 0.0;
    for (int i = 0; i < n; ++i) {
        const double zi = y[off + i] * (5.12 / 100.0);
        f += zi * zi - 10.0 * std::cos(2.0 * 3.1415926535897932384626433832795029 * zi) + 10.0;
    }
    return f;
}

inline double rosenbrock_sub(const Vec& y, int off, int n) {
    if (n == 0) return 0.0;
    Vec z(n);
    for (int i = 0; i < n; ++i) z[i] = y[off + i] * (2.048 / 100.0);
    z[0] += 1.0;
    double f = 0.0;
    for (int i = 0; i < n - 1; ++i) {
        z[i + 1] += 1.0;
        const double tmp1 = z[i] * z[i] - z[i + 1];
        const double tmp2 = z[i] - 1.0;
        f += 100.0 * tmp1 * tmp1 + tmp2 * tmp2;
    }
    return f;
}

// Hybrid Function 5, per the official reference: shift+rotate once, shuffle
// via the fixed permutation S, split into 4 groups (proportions
// 0.2/0.2/0.3/0.3 of D, last group takes the remainder), and sum BentCigar +
// HGBat + Rastrigin + Rosenbrock over the four groups in turn.
inline double hf05_func(const Vec& x, int nx, const double* Os, const double* Mr,
                        const int* S) {
    Vec y;
    shiftfunc(x, y, Os, nx);
    Vec z;
    rotatefunc(y, z, Mr, nx);

    Vec shuffled(nx);
    for (int i = 0; i < nx; ++i) shuffled[i] = z[S[i] - 1];

    const double Gp[4] = {0.2, 0.2, 0.3, 0.3};
    int Gnx[4];
    int used = 0;
    for (int i = 0; i < 3; ++i) {
        Gnx[i] = static_cast<int>(std::ceil(Gp[i] * double(nx)));
        used += Gnx[i];
    }
    Gnx[3] = nx - used;

    const int off0 = 0;
    const int off1 = Gnx[0];
    const int off2 = Gnx[0] + Gnx[1];
    const int off3 = Gnx[0] + Gnx[1] + Gnx[2];

    const double f0 = bent_cigar_sub(shuffled, off0, Gnx[0]);
    const double f1 = hgbat_sub(shuffled, off1, Gnx[1]);
    const double f2 = rastrigin_sub(shuffled, off2, Gnx[2]);
    const double f3 = rosenbrock_sub(shuffled, off3, Gnx[3]);
    return f0 + f1 + f2 + f3;
}

