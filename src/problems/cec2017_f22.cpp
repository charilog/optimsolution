inline void shiftfunc(const Vec& x, Vec& xshift, const double* Os, int nx) {
    xshift.resize(nx);
    for (int i = 0; i < nx; ++i) xshift[i] = x[i] - Os[i];
}

inline void rotatefunc(const Vec& x, Vec& xrot, const double* Mr, int nx) {
    xrot.assign(nx, 0.0);
    for (int i = 0; i < nx; ++i) {
        double acc = 0.0;
        for (int j = 0; j < nx; ++j) acc += x[j] * Mr[i * nx + j];
        xrot[i] = acc;
    }
}

inline void sr_func(const Vec& x, Vec& sr_x, int nx, const double* Os, const double* Mr,
                    double sh_rate) {
    Vec y;
    shiftfunc(x, y, Os, nx);
    for (int i = 0; i < nx; ++i) y[i] *= sh_rate;
    rotatefunc(y, sr_x, Mr, nx);
}

inline double rastrigin_raw(const Vec& z) {
    double f = 0.0;
    for (double zi : z) f += zi * zi - 10.0 * std::cos(2.0 * kPi * zi) + 10.0;
    return f;
}

inline double griewank_raw(const Vec& z) {
    const int n = static_cast<int>(z.size());
    double s = 0.0, p = 1.0;
    for (int i = 0; i < n; ++i) {
        s += z[i] * z[i];
        p *= std::cos(z[i] / std::sqrt(1.0 + double(i)));
    }
    return 1.0 + s / 4000.0 - p;
}

inline double schwefel_raw(const Vec& zIn) {
    const int n = static_cast<int>(zIn.size());
    double f = 0.0;
    for (int i = 0; i < n; ++i) {
        double zi = zIn[i] + 4.209687462275036e+002;
        if (zi > 500.0) {
            const double r = 500.0 - std::fmod(zi, 500.0);
            f -= r * std::sin(std::sqrt(r));
            const double tmp = (zi - 500.0) / 100.0;
            f += tmp * tmp / double(n);
        } else if (zi < -500.0) {
            const double r = 500.0 - std::fmod(std::fabs(zi), 500.0);
            f -= (-500.0 + std::fmod(std::fabs(zi), 500.0)) * std::sin(std::sqrt(r));
            const double tmp = (zi + 500.0) / 100.0;
            f += tmp * tmp / double(n);
        } else {
            f -= zi * std::sin(std::sqrt(std::fabs(zi)));
        }
    }
    f += 4.189828872724338e+002 * double(n);
    return f;
}

inline double cf_cal(const Vec& x, int nx, const double* Os, const double* delta,
                     const double* bias, double* fit, int cf_num) {
    std::vector<double> w(cf_num, 0.0);
    double w_max = 0.0, w_sum = 0.0;
    for (int i = 0; i < cf_num; ++i) {
        fit[i] += bias[i];
        double dist2 = 0.0;
        for (int j = 0; j < nx; ++j) {
            const double d = x[j] - Os[i * nx + j];
            dist2 += d * d;
        }
        if (dist2 != 0.0) {
            w[i] = std::pow(1.0 / dist2, 0.5) * std::exp(-dist2 / (2.0 * nx * delta[i] * delta[i]));
        } else {
            w[i] = kInf;
        }
        if (w[i] > w_max) w_max = w[i];
        w_sum += w[i];
    }
    if (w_max == 0.0) {
        std::fill(w.begin(), w.end(), 1.0);
        w_sum = double(cf_num);
    }
    double f = 0.0;
    for (int i = 0; i < cf_num; ++i) f += (w[i] / w_sum) * fit[i];
    return f;
}

