void CEC2017F22::init(int dim) {
    if (!(dim == 10 || dim == 30 || dim == 50)) {
        throw std::invalid_argument("CEC2017F22 supports only dimensions 10, 30, and 50.");
    }
    Problem::init(dim);
    Vec lo(dim, -100.0), hi(dim, 100.0);
    setBounds(lo, hi);
    load_embedded_data(dim);

    Vec xopt(shift_.begin(), shift_.begin() + dim);
    setKnownGlobalOptimum(2200.0, xopt);
}

void CEC2017F22::load_embedded_data(int dim) {
    const double* s = shift_data_for_dim(dim);
    const double* r = rotation_data_for_dim(dim);
    if (!s || !r) {
        throw std::runtime_error("Missing embedded CEC2017 F22 data.");
    }
    shift_.assign(s, s + 3 * dim);
    rotation_.assign(r, r + 3 * dim * dim);
}

