constexpr double kPi = 3.1415926535897932384626433832795029;

// Lunacek Bi-Rastrigin, per the official reference's bespoke pipeline
// (this function does not use the shared sr_func() helper).
inline double bi_rastrigin_func(const Vec& x, int nx, const double* Os, const double* Mr) {
    const double mu0 = 2.5;
    const double d = 1.0;
    const double s = 1.0 - 1.0 / (2.0 * std::sqrt(double(nx) + 20.0) - 8.2);
    const double mu1 = -std::sqrt((mu0 * mu0 - d) / s);

    Vec y(nx), z(nx);
    for (int i = 0; i < nx; ++i) {
        y[i] = (x[i] - Os[i]) * (10.0 / 100.0);
    }
    for (int i = 0; i < nx; ++i) {
        double zi = 2.0 * y[i];
        if (Os[i] < 0.0) zi *= -1.0;
        z[i] = zi;
    }

    double tmp1 = 0.0, tmp2 = 0.0;
    for (int i = 0; i < nx; ++i) {
        const double a = z[i];               // (z_i + mu0) - mu0
        const double b = z[i] + mu0 - mu1;    // (z_i + mu0) - mu1
        tmp1 += a * a;
        tmp2 += b * b;
    }
    tmp2 = tmp2 * s + d * double(nx);

    Vec w(nx, 0.0);
    for (int i = 0; i < nx; ++i) {
        double acc = 0.0;
        for (int j = 0; j < nx; ++j) acc += z[j] * Mr[i * nx + j];
        w[i] = acc;
    }
    double cosSum = 0.0;
    for (int i = 0; i < nx; ++i) cosSum += std::cos(2.0 * kPi * w[i]);

    const double best = std::min(tmp1, tmp2);
    return best + 10.0 * (double(nx) - cosSum);
}

