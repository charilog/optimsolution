constexpr double kPi = 3.1415926535897932384626433832795029;

inline void shiftfunc(const Vec& x, Vec& xshift, const double* Os, int nx) {
    xshift.resize(nx);
    for (int i = 0; i < nx; ++i) xshift[i] = x[i] - Os[i];
}

inline void rotatefunc(const Vec& x, Vec& xrot, const double* Mr, int nx) {
    xrot.assign(nx, 0.0);
    for (int i = 0; i < nx; ++i) {
        double acc = 0.0;
        for (int j = 0; j < nx; ++j) acc += x[j] * Mr[i * nx + j];
        xrot[i] = acc;
    }
}

inline double bent_cigar_sub(const Vec& y, int off, int n) {
    double f = y[off] * y[off];
    for (int i = 1; i < n; ++i) f += 1.0e6 * y[off + i] * y[off + i];
    return f;
}

inline double rosenbrock_sub(const Vec& y, int off, int n) {
    if (n == 0) return 0.0;
    Vec z(n);
    for (int i = 0; i < n; ++i) z[i] = y[off + i] * (2.048 / 100.0);
    z[0] += 1.0;
    double f = 0.0;
    for (int i = 0; i < n - 1; ++i) {
        z[i + 1] += 1.0;
        const double tmp1 = z[i] * z[i] - z[i + 1];
        const double tmp2 = z[i] - 1.0;
        f += 100.0 * tmp1 * tmp1 + tmp2 * tmp2;
    }
    return f;
}

// Lunacek Bi-Rastrigin sub-function. NOTE (see cec2017_f13.h class comment):
// the official reference passes the FULL, unsliced shift vector `OsFull`
// here (not offset to this group's own position) for the sign-flip
// decision -- this is a verified reference-code quirk that must be
// replicated, not "fixed", to stay numerically identical to the official
// results. `OsFull` is indexed 0..n-1 directly, exactly as the reference
// code does.
inline double bi_rastrigin_sub(const Vec& y, int off, int n, const double* OsFull) {
    const double mu0 = 2.5;
    const double d = 1.0;
    const double s = 1.0 - 1.0 / (2.0 * std::sqrt(double(n) + 20.0) - 8.2);
    const double mu1 = -std::sqrt((mu0 * mu0 - d) / s);

    Vec yy(n), z(n), tmpx(n);
    for (int i = 0; i < n; ++i) yy[i] = y[off + i] * (10.0 / 100.0); // s_flag=0: copy, then *=0.1
    for (int i = 0; i < n; ++i) {
        double v = 2.0 * yy[i];
        if (OsFull[i] < 0.0) v *= -1.0; // quirk: OsFull[0..n-1], not offset by this group
        tmpx[i] = v;
    }
    for (int i = 0; i < n; ++i) z[i] = tmpx[i];
    for (int i = 0; i < n; ++i) tmpx[i] += mu0;

    double tmp1 = 0.0, tmp2 = 0.0;
    for (int i = 0; i < n; ++i) {
        double a = tmpx[i] - mu0;
        double b = tmpx[i] - mu1;
        tmp1 += a * a;
        tmp2 += b * b;
    }
    tmp2 = tmp2 * s + d * double(n);

    // r_flag=0 branch: cosine sum taken directly over z (no rotation).
    double tmpc = 0.0;
    for (int i = 0; i < n; ++i) tmpc += std::cos(2.0 * kPi * z[i]);

    return std::min(tmp1, tmp2) + 10.0 * (double(n) - tmpc);
}

// Hybrid Function 3, per the official reference: shift+rotate once, shuffle
// via the fixed permutation S, split into 3 groups (proportions 0.3/0.3/0.4
// of D, last group takes the remainder), and sum BentCigar + Rosenbrock +
// BiRastrigin over the three groups in turn.
inline double hf03_func(const Vec& x, int nx, const double* Os, const double* Mr,
                        const int* S) {
    Vec y;
    shiftfunc(x, y, Os, nx);
    Vec z;
    rotatefunc(y, z, Mr, nx);

    Vec shuffled(nx);
    for (int i = 0; i < nx; ++i) shuffled[i] = z[S[i] - 1];

    const double Gp[3] = {0.3, 0.3, 0.4};
    int Gnx[3];
    int used = 0;
    for (int i = 0; i < 2; ++i) {
        Gnx[i] = static_cast<int>(std::ceil(Gp[i] * double(nx)));
        used += Gnx[i];
    }
    Gnx[2] = nx - used;

    const int off0 = 0;
    const int off1 = Gnx[0];
    const int off2 = Gnx[0] + Gnx[1];

    const double f0 = bent_cigar_sub(shuffled, off0, Gnx[0]);
    const double f1 = rosenbrock_sub(shuffled, off1, Gnx[1]);
    const double f2 = bi_rastrigin_sub(shuffled, off2, Gnx[2], Os);
    return f0 + f1 + f2;
}

