void CEC2017F5::init(int dim) {
    if (!(dim == 10 || dim == 30 || dim == 50)) {
        throw std::invalid_argument("CEC2017F5 supports only dimensions 10, 30, and 50.");
    }
    Problem::init(dim);
    Vec lo(dim, -100.0), hi(dim, 100.0);
    setBounds(lo, hi);
    load_embedded_data(dim);

    // Global minimum: f(x*) = 500 (f_bias) at x* = o (the shift vector).
    setKnownGlobalOptimum(500.0, shift_);
}

void CEC2017F5::load_embedded_data(int dim) {
    const double* s = shift_data_for_dim(dim);
    const double* r = rotation_data_for_dim(dim);
    if (!s || !r) {
        throw std::runtime_error("Missing embedded CEC2017 F5 data.");
    }
    shift_.assign(s, s + dim);
    rotation_.assign(r, r + dim * dim);
}

double CEC2017F5::evaluate_core(const Vec& x) {
    const int D = dimension();
    if (static_cast<int>(x.size()) != D) {
        throw std::invalid_argument("CEC2017F5::evaluate_core received vector with wrong dimension.");
    }
    const double f = rastrigin_func(x, D, shift_.data(), rotation_.data(), true, true) + 500.0;
    return std::isfinite(f) ? f : 1e12;
}

