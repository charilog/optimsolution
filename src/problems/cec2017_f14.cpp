constexpr double kPi = 3.1415926535897932384626433832795029;
constexpr double kE  = 2.7182818284590452353602874713526625;

inline void shiftfunc(const Vec& x, Vec& xshift, const double* Os, int nx) {
    xshift.resize(nx);
    for (int i = 0; i < nx; ++i) xshift[i] = x[i] - Os[i];
}

inline void rotatefunc(const Vec& x, Vec& xrot, const double* Mr, int nx) {
    xrot.assign(nx, 0.0);
    for (int i = 0; i < nx; ++i) {
        double acc = 0.0;
        for (int j = 0; j < nx; ++j) acc += x[j] * Mr[i * nx + j];
        xrot[i] = acc;
    }
}

inline double ellips_sub(const Vec& y, int off, int n) {
    if (n == 1) return y[off] * y[off];
    double f = 0.0;
    for (int i = 0; i < n; ++i) {
        f += std::pow(10.0, 6.0 * i / double(n - 1)) * y[off + i] * y[off + i];
    }
    return f;
}

inline double ackley_sub(const Vec& y, int off, int n) {
    double sum1 = 0.0, sum2 = 0.0;
    for (int i = 0; i < n; ++i) {
        const double zi = y[off + i];
        sum1 += zi * zi;
        sum2 += std::cos(2.0 * kPi * zi);
    }
    sum1 = -0.2 * std::sqrt(sum1 / double(n));
    sum2 /= double(n);
    return kE - 20.0 * std::exp(sum1) - std::exp(sum2) + 20.0;
}

inline double rastrigin_sub(const Vec& y, int off, int n) {
    double f = 0.0;
    for (int i = 0; i < n; ++i) {
        const double zi = y[off + i] * (5.12 / 100.0);
        f += zi * zi - 10.0 * std::cos(2.0 * kPi * zi) + 10.0;
    }
    return f;
}

// Expanded Scaffer's F6 sub-function. NOTE (see cec2017_f14.h class
// comment): the official reference has a verified buffer-aliasing quirk
// here -- it reads the FIRST n elements of the WHOLE shuffled vector
// (`yFull`, starting at index 0), not this group's own slice at `off`.
// This mirrors the same quirk documented for the standalone F6.
inline double schaffer_f6_sub_quirky(const Vec& yFull, int n) {
    double f = 0.0;
    for (int i = 0; i < n - 1; ++i) {
        const double w = std::sqrt(yFull[i] * yFull[i] + yFull[i + 1] * yFull[i + 1]);
        const double tmp = std::sin(50.0 * std::pow(w, 0.2));
        f += std::sqrt(w) + std::sqrt(w) * tmp * tmp;
    }
    const double denom = double(n - 1);
    return f * f / (denom * denom);
}

// Hybrid Function 4, per the official reference: shift+rotate once, shuffle
// via the fixed permutation S, split into 4 groups (proportions
// 0.2/0.2/0.2/0.4 of D, last group takes the remainder), and sum Ellip +
// Ackley + ScafferF6(quirky) + Rastrigin over the four groups in turn.
inline double hf04_func(const Vec& x, int nx, const double* Os, const double* Mr,
                        const int* S) {
    Vec y;
    shiftfunc(x, y, Os, nx);
    Vec z;
    rotatefunc(y, z, Mr, nx);

    Vec shuffled(nx);
    for (int i = 0; i < nx; ++i) shuffled[i] = z[S[i] - 1];

    const double Gp[4] = {0.2, 0.2, 0.2, 0.4};
    int Gnx[4];
    int used = 0;
    for (int i = 0; i < 3; ++i) {
        Gnx[i] = static_cast<int>(std::ceil(Gp[i] * double(nx)));
        used += Gnx[i];
    }
    Gnx[3] = nx - used;

    const int off0 = 0;
    const int off1 = Gnx[0];
    const int off2 = Gnx[0] + Gnx[1];
    const int off3 = Gnx[0] + Gnx[1] + Gnx[2];

    const double f0 = ellips_sub(shuffled, off0, Gnx[0]);
    const double f1 = ackley_sub(shuffled, off1, Gnx[1]);
    const double f2 = schaffer_f6_sub_quirky(shuffled, Gnx[2]); // quirk: reads shuffled[0..Gnx[2]-1]
    const double f3 = rastrigin_sub(shuffled, off3, Gnx[3]);
    return f0 + f1 + f2 + f3;
}

