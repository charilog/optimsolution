inline void shiftfunc(const Vec& x, Vec& xshift, const double* Os, int nx) {
    xshift.resize(nx);
    for (int i = 0; i < nx; ++i) xshift[i] = x[i] - Os[i];
}

inline void rotatefunc(const Vec& x, Vec& xrot, const double* Mr, int nx) {
    xrot.assign(nx, 0.0);
    for (int i = 0; i < nx; ++i) {
        double acc = 0.0;
        for (int j = 0; j < nx; ++j) acc += x[j] * Mr[i * nx + j];
        xrot[i] = acc;
    }
}

// Sub-function building blocks, unscaled/unshifted -- the single top-level
// shift+rotate (see hf01_func below) already happened once; per the
// official reference, each sub-function here only applies its own internal
// scale factor to its slice of the already-shifted+rotated+shuffled vector.

inline double zakharov_sub(const Vec& y, int off, int n) {
    double sum1 = 0.0, sum2 = 0.0;
    for (int i = 0; i < n; ++i) {
        const double zi = y[off + i];
        sum1 += zi * zi;
        sum2 += 0.5 * double(i + 1) * zi;
    }
    return sum1 + sum2 * sum2 + sum2 * sum2 * sum2 * sum2;
}

inline double rosenbrock_sub(const Vec& y, int off, int n) {
    if (n == 0) return 0.0;
    Vec z(n);
    for (int i = 0; i < n; ++i) z[i] = y[off + i] * (2.048 / 100.0);
    z[0] += 1.0;
    double f = 0.0;
    for (int i = 0; i < n - 1; ++i) {
        z[i + 1] += 1.0;
        const double tmp1 = z[i] * z[i] - z[i + 1];
        const double tmp2 = z[i] - 1.0;
        f += 100.0 * tmp1 * tmp1 + tmp2 * tmp2;
    }
    return f;
}

inline double rastrigin_sub(const Vec& y, int off, int n) {
    double f = 0.0;
    for (int i = 0; i < n; ++i) {
        const double zi = y[off + i] * (5.12 / 100.0);
        f += zi * zi - 10.0 * std::cos(2.0 * 3.1415926535897932384626433832795029 * zi) + 10.0;
    }
    return f;
}

// Hybrid Function 1, per the official reference: shift+rotate once, shuffle
// via the fixed permutation S, split into 3 groups (proportions 0.2/0.4/0.4
// of D, last group takes the remainder), and sum Zakharov + Rosenbrock +
// Rastrigin over the three groups in turn.
inline double hf01_func(const Vec& x, int nx, const double* Os, const double* Mr,
                        const int* S) {
    Vec y;
    shiftfunc(x, y, Os, nx);
    Vec z;
    rotatefunc(y, z, Mr, nx);

    Vec shuffled(nx);
    for (int i = 0; i < nx; ++i) shuffled[i] = z[S[i] - 1]; // S is 1-indexed as stored

    const double Gp[3] = {0.2, 0.4, 0.4};
    int Gnx[3];
    int used = 0;
    for (int i = 0; i < 2; ++i) {
        Gnx[i] = static_cast<int>(std::ceil(Gp[i] * double(nx)));
        used += Gnx[i];
    }
    Gnx[2] = nx - used;

    const int off0 = 0;
    const int off1 = Gnx[0];
    const int off2 = Gnx[0] + Gnx[1];

    const double f0 = zakharov_sub(shuffled, off0, Gnx[0]);
    const double f1 = rosenbrock_sub(shuffled, off1, Gnx[1]);
    const double f2 = rastrigin_sub(shuffled, off2, Gnx[2]);
    return f0 + f1 + f2;
}

