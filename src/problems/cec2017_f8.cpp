constexpr double kPi = 3.1415926535897932384626433832795029;

inline void shiftfunc(const Vec& x, Vec& xshift, const double* Os, int nx) {
    xshift.resize(nx);
    for (int i = 0; i < nx; ++i) xshift[i] = x[i] - Os[i];
}

inline void rotatefunc(const Vec& x, Vec& xrot, const double* Mr, int nx) {
    xrot.assign(nx, 0.0);
    for (int i = 0; i < nx; ++i) {
        double acc = 0.0;
        for (int j = 0; j < nx; ++j) acc += x[j] * Mr[i * nx + j];
        xrot[i] = acc;
    }
}

inline void sr_func(const Vec& x, Vec& sr_x, int nx, const double* Os, const double* Mr,
                    double sh_rate, bool s_flag, bool r_flag) {
    Vec y(nx, 0.0);
    if (s_flag) {
        if (r_flag) {
            shiftfunc(x, y, Os, nx);
            for (int i = 0; i < nx; ++i) y[i] *= sh_rate;
            rotatefunc(y, sr_x, Mr, nx);
        } else {
            shiftfunc(x, sr_x, Os, nx);
            for (int i = 0; i < nx; ++i) sr_x[i] *= sh_rate;
        }
    } else {
        if (r_flag) {
            for (int i = 0; i < nx; ++i) y[i] = x[i] * sh_rate;
            rotatefunc(y, sr_x, Mr, nx);
        } else {
            sr_x.resize(nx);
            for (int i = 0; i < nx; ++i) sr_x[i] = x[i] * sh_rate;
        }
    }
}

// step_rastrigin, per the official reference (sh_rate = 5.12/100).
// NOTE: intentionally does NOT apply the non-continuous "snap to grid"
// step -- see the class-level comment in cec2017_f8.h for why the official
// reference's own snapping has no effect on its published results, and why
// this implementation deliberately mirrors that rather than "fixing" it.
inline double step_rastrigin_func(const Vec& x, int nx, const double* Os, const double* Mr,
                                  bool s_flag, bool r_flag) {
    Vec z;
    sr_func(x, z, nx, Os, Mr, 5.12 / 100.0, s_flag, r_flag);
    double f = 0.0;
    for (int i = 0; i < nx; ++i) {
        f += z[i] * z[i] - 10.0 * std::cos(2.0 * kPi * z[i]) + 10.0;
    }
    return f;
}

