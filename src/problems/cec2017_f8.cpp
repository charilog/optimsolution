void CEC2017F8::init(int dim) {
    if (!(dim == 10 || dim == 30 || dim == 50)) {
        throw std::invalid_argument("CEC2017F8 supports only dimensions 10, 30, and 50.");
    }
    Problem::init(dim);
    Vec lo(dim, -100.0), hi(dim, 100.0);
    setBounds(lo, hi);
    load_embedded_data(dim);

    // Global minimum: f(x*) = 800 (f_bias) at x* = o (the shift vector).
    setKnownGlobalOptimum(800.0, shift_);
}

void CEC2017F8::load_embedded_data(int dim) {
    const double* s = shift_data_for_dim(dim);
    const double* r = rotation_data_for_dim(dim);
    if (!s || !r) {
        throw std::runtime_error("Missing embedded CEC2017 F8 data.");
    }
    shift_.assign(s, s + dim);
    rotation_.assign(r, r + dim * dim);
}

