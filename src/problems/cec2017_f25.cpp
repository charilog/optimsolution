inline void shiftfunc(const Vec& x, Vec& xshift, const double* Os, int nx) {
    xshift.resize(nx);
    for (int i = 0; i < nx; ++i) xshift[i] = x[i] - Os[i];
}

inline void rotatefunc(const Vec& x, Vec& xrot, const double* Mr, int nx) {
    xrot.assign(nx, 0.0);
    for (int i = 0; i < nx; ++i) {
        double acc = 0.0;
        for (int j = 0; j < nx; ++j) acc += x[j] * Mr[i * nx + j];
        xrot[i] = acc;
    }
}

inline void sr_func(const Vec& x, Vec& sr_x, int nx, const double* Os, const double* Mr,
                    double sh_rate) {
    Vec y;
    shiftfunc(x, y, Os, nx);
    for (int i = 0; i < nx; ++i) y[i] *= sh_rate;
    rotatefunc(y, sr_x, Mr, nx);
}

inline double rastrigin_raw(const Vec& z) {
    double f = 0.0;
    for (double zi : z) f += zi * zi - 10.0 * std::cos(2.0 * kPi * zi) + 10.0;
    return f;
}

// HappyCat: caller must pass z already shifted by -1 per element (matching
// the official code's in-place "z[i] -= 1" step) via the `minusOne` flag.
inline double happycat_raw(Vec z) {
    const int n = static_cast<int>(z.size());
    double r2 = 0.0, sumz = 0.0;
    for (int i = 0; i < n; ++i) {
        z[i] -= 1.0;
        r2 += z[i] * z[i];
        sumz += z[i];
    }
    const double alpha = 1.0 / 8.0;
    return std::pow(std::fabs(r2 - double(n)), 2.0 * alpha) + (0.5 * r2 + sumz) / double(n) + 0.5;
}

inline double ackley_raw(const Vec& z) {
    const int n = static_cast<int>(z.size());
    double sum1 = 0.0, sum2 = 0.0;
    for (int i = 0; i < n; ++i) {
        sum1 += z[i] * z[i];
        sum2 += std::cos(2.0 * kPi * z[i]);
    }
    sum1 = -0.2 * std::sqrt(sum1 / double(n));
    sum2 /= double(n);
    return kE - 20.0 * std::exp(sum1) - std::exp(sum2) + 20.0;
}

inline double discus_raw(const Vec& z) {
    const int n = static_cast<int>(z.size());
    double f = 1.0e6 * z[0] * z[0];
    for (int i = 1; i < n; ++i) f += z[i] * z[i];
    return f;
}

inline double rosenbrock_raw(Vec z) {
    const int n = static_cast<int>(z.size());
    if (n == 0) return 0.0;
    z[0] += 1.0;
    double f = 0.0;
    for (int i = 0; i < n - 1; ++i) {
        z[i + 1] += 1.0;
        const double tmp1 = z[i] * z[i] - z[i + 1];
        const double tmp2 = z[i] - 1.0;
        f += 100.0 * tmp1 * tmp1 + tmp2 * tmp2;
    }
    return f;
}

inline double cf_cal(const Vec& x, int nx, const double* Os, const double* delta,
                     const double* bias, double* fit, int cf_num) {
    std::vector<double> w(cf_num, 0.0);
    double w_max = 0.0, w_sum = 0.0;
    for (int i = 0; i < cf_num; ++i) {
        fit[i] += bias[i];
        double dist2 = 0.0;
        for (int j = 0; j < nx; ++j) {
            const double d = x[j] - Os[i * nx + j];
            dist2 += d * d;
        }
        if (dist2 != 0.0) {
            w[i] = std::pow(1.0 / dist2, 0.5) * std::exp(-dist2 / (2.0 * nx * delta[i] * delta[i]));
        } else {
            w[i] = kInf;
        }
        if (w[i] > w_max) w_max = w[i];
        w_sum += w[i];
    }
    if (w_max == 0.0) {
        std::fill(w.begin(), w.end(), 1.0);
        w_sum = double(cf_num);
    }
    double f = 0.0;
    for (int i = 0; i < cf_num; ++i) f += (w[i] / w_sum) * fit[i];
    return f;
}

