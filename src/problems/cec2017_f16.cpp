inline void shiftfunc(const Vec& x, Vec& xshift, const double* Os, int nx) {
    xshift.resize(nx);
    for (int i = 0; i < nx; ++i) xshift[i] = x[i] - Os[i];
}

inline void rotatefunc(const Vec& x, Vec& xrot, const double* Mr, int nx) {
    xrot.assign(nx, 0.0);
    for (int i = 0; i < nx; ++i) {
        double acc = 0.0;
        for (int j = 0; j < nx; ++j) acc += x[j] * Mr[i * nx + j];
        xrot[i] = acc;
    }
}

// Expanded Scaffer's F6, circular/wrap-around variant (distinct from the
// standalone F6's schaffer_F7_func -- see the class-level comment in
// cec2017_f16.h). No buffer-aliasing quirk here.
inline double escaffer6_sub(const Vec& y, int off, int n) {
    double f = 0.0;
    for (int i = 0; i < n - 1; ++i) {
        const double a = y[off + i], b = y[off + i + 1];
        const double s = std::sin(std::sqrt(a * a + b * b));
        const double t1 = s * s;
        const double t2 = 1.0 + 0.001 * (a * a + b * b);
        f += 0.5 + (t1 - 0.5) / (t2 * t2);
    }
    const double a = y[off + n - 1], b = y[off];
    const double s = std::sin(std::sqrt(a * a + b * b));
    const double t1 = s * s;
    const double t2 = 1.0 + 0.001 * (a * a + b * b);
    f += 0.5 + (t1 - 0.5) / (t2 * t2);
    return f;
}

inline double hgbat_sub(const Vec& y, int off, int n) {
    Vec z(n);
    double r2 = 0.0, sumz = 0.0;
    for (int i = 0; i < n; ++i) {
        const double zi = y[off + i] * (5.0 / 100.0) - 1.0;
        z[i] = zi;
        r2 += zi * zi;
        sumz += zi;
    }
    const double alpha = 0.25;
    return std::pow(std::fabs(r2 * r2 - sumz * sumz), 2.0 * alpha) + (0.5 * r2 + sumz) / double(n) + 0.5;
}

inline double rosenbrock_sub(const Vec& y, int off, int n) {
    if (n == 0) return 0.0;
    Vec z(n);
    for (int i = 0; i < n; ++i) z[i] = y[off + i] * (2.048 / 100.0);
    z[0] += 1.0;
    double f = 0.0;
    for (int i = 0; i < n - 1; ++i) {
        z[i + 1] += 1.0;
        const double tmp1 = z[i] * z[i] - z[i + 1];
        const double tmp2 = z[i] - 1.0;
        f += 100.0 * tmp1 * tmp1 + tmp2 * tmp2;
    }
    return f;
}

inline double schwefel_sub(const Vec& y, int off, int n) {
    double f = 0.0;
    for (int i = 0; i < n; ++i) {
        double zi = y[off + i] * (1000.0 / 100.0) + 4.209687462275036e+002;
        if (zi > 500.0) {
            const double r = 500.0 - std::fmod(zi, 500.0);
            f -= r * std::sin(std::sqrt(r));
            const double tmp = (zi - 500.0) / 100.0;
            f += tmp * tmp / double(n);
        } else if (zi < -500.0) {
            const double r = 500.0 - std::fmod(std::fabs(zi), 500.0);
            f -= (-500.0 + std::fmod(std::fabs(zi), 500.0)) * std::sin(std::sqrt(r));
            const double tmp = (zi + 500.0) / 100.0;
            f += tmp * tmp / double(n);
        } else {
            f -= zi * std::sin(std::sqrt(std::fabs(zi)));
        }
    }
    f += 4.189828872724338e+002 * double(n);
    return f;
}

// Hybrid Function 6, per the official reference: shift+rotate once, shuffle
// via the fixed permutation S, split into 4 groups (proportions
// 0.2/0.2/0.3/0.3 of D, last group takes the remainder), and sum ScafferF6 +
// HGBat + Rosenbrock + Schwefel over the four groups in turn.
inline double hf06_func(const Vec& x, int nx, const double* Os, const double* Mr,
                        const int* S) {
    Vec y;
    shiftfunc(x, y, Os, nx);
    Vec z;
    rotatefunc(y, z, Mr, nx);

    Vec shuffled(nx);
    for (int i = 0; i < nx; ++i) shuffled[i] = z[S[i] - 1];

    const double Gp[4] = {0.2, 0.2, 0.3, 0.3};
    int Gnx[4];
    int used = 0;
    for (int i = 0; i < 3; ++i) {
        Gnx[i] = static_cast<int>(std::ceil(Gp[i] * double(nx)));
        used += Gnx[i];
    }
    Gnx[3] = nx - used;

    const int off0 = 0;
    const int off1 = Gnx[0];
    const int off2 = Gnx[0] + Gnx[1];
    const int off3 = Gnx[0] + Gnx[1] + Gnx[2];

    const double f0 = escaffer6_sub(shuffled, off0, Gnx[0]);
    const double f1 = hgbat_sub(shuffled, off1, Gnx[1]);
    const double f2 = rosenbrock_sub(shuffled, off2, Gnx[2]);
    const double f3 = schwefel_sub(shuffled, off3, Gnx[3]);
    return f0 + f1 + f2 + f3;
}

