constexpr double kPi = 3.1415926535897932384626433832795029;
constexpr double kE  = 2.7182818284590452353602874713526625;

inline void shiftfunc(const Vec& x, Vec& xshift, const double* Os, int nx) {
    xshift.resize(nx);
    for (int i = 0; i < nx; ++i) xshift[i] = x[i] - Os[i];
}

inline void rotatefunc(const Vec& x, Vec& xrot, const double* Mr, int nx) {
    xrot.assign(nx, 0.0);
    for (int i = 0; i < nx; ++i) {
        double acc = 0.0;
        for (int j = 0; j < nx; ++j) acc += x[j] * Mr[i * nx + j];
        xrot[i] = acc;
    }
}

// Katsuura, scale 5/100 (confirmed against the reference source -- easy to
// mis-transcribe as unscaled, see the class-level comment in cec2017_f17.h).
inline double katsuura_sub(const Vec& y, int off, int n) {
    double f = 1.0;
    const double tmp3 = std::pow(double(n), 1.2);
    for (int i = 0; i < n; ++i) {
        const double zi = y[off + i] * (5.0 / 100.0);
        double temp = 0.0;
        for (int j = 1; j <= 32; ++j) {
            const double t1 = std::pow(2.0, double(j));
            const double t2 = t1 * zi;
            temp += std::fabs(t2 - std::floor(t2 + 0.5)) / t1;
        }
        f *= std::pow(1.0 + double(i + 1) * temp, 10.0 / tmp3);
    }
    const double tmp1 = 10.0 / double(n) / double(n);
    return f * tmp1 - tmp1;
}

inline double ackley_sub(const Vec& y, int off, int n) {
    double sum1 = 0.0, sum2 = 0.0;
    for (int i = 0; i < n; ++i) {
        const double zi = y[off + i];
        sum1 += zi * zi;
        sum2 += std::cos(2.0 * kPi * zi);
    }
    sum1 = -0.2 * std::sqrt(sum1 / double(n));
    sum2 /= double(n);
    return kE - 20.0 * std::exp(sum1) - std::exp(sum2) + 20.0;
}

// Griewank-Rosenbrock, scale 5/100, circular/wrap-around variant.
inline double grie_rosen_sub(const Vec& y, int off, int n) {
    if (n == 0) return 0.0;
    Vec z(n);
    for (int i = 0; i < n; ++i) z[i] = y[off + i] * (5.0 / 100.0);
    z[0] += 1.0;
    double f = 0.0;
    for (int i = 0; i < n - 1; ++i) {
        z[i + 1] += 1.0;
        const double tmp1 = z[i] * z[i] - z[i + 1];
        const double tmp2 = z[i] - 1.0;
        const double temp = 100.0 * tmp1 * tmp1 + tmp2 * tmp2;
        f += temp * temp / 4000.0 - std::cos(temp) + 1.0;
    }
    const double tmp1 = z[n - 1] * z[n - 1] - z[0];
    const double tmp2 = z[n - 1] - 1.0;
    const double temp = 100.0 * tmp1 * tmp1 + tmp2 * tmp2;
    f += temp * temp / 4000.0 - std::cos(temp) + 1.0;
    return f;
}

inline double schwefel_sub(const Vec& y, int off, int n) {
    double f = 0.0;
    for (int i = 0; i < n; ++i) {
        double zi = y[off + i] * (1000.0 / 100.0) + 4.209687462275036e+002;
        if (zi > 500.0) {
            const double r = 500.0 - std::fmod(zi, 500.0);
            f -= r * std::sin(std::sqrt(r));
            const double tmp = (zi - 500.0) / 100.0;
            f += tmp * tmp / double(n);
        } else if (zi < -500.0) {
            const double r = 500.0 - std::fmod(std::fabs(zi), 500.0);
            f -= (-500.0 + std::fmod(std::fabs(zi), 500.0)) * std::sin(std::sqrt(r));
            const double tmp = (zi + 500.0) / 100.0;
            f += tmp * tmp / double(n);
        } else {
            f -= zi * std::sin(std::sqrt(std::fabs(zi)));
        }
    }
    f += 4.189828872724338e+002 * double(n);
    return f;
}

inline double rastrigin_sub(const Vec& y, int off, int n) {
    double f = 0.0;
    for (int i = 0; i < n; ++i) {
        const double zi = y[off + i] * (5.12 / 100.0);
        f += zi * zi - 10.0 * std::cos(2.0 * kPi * zi) + 10.0;
    }
    return f;
}

// Hybrid Function 7, per the official reference: shift+rotate once, shuffle
// via the fixed permutation S, split into 5 groups (proportions
// 0.1/0.2/0.2/0.2/0.3 of D, last group takes the remainder), and sum
// Katsuura + Ackley + GrieRosen + Schwefel + Rastrigin over the five groups
// in turn.
inline double hf07_func(const Vec& x, int nx, const double* Os, const double* Mr,
                        const int* S) {
    Vec y;
    shiftfunc(x, y, Os, nx);
    Vec z;
    rotatefunc(y, z, Mr, nx);

    Vec shuffled(nx);
    for (int i = 0; i < nx; ++i) shuffled[i] = z[S[i] - 1];

    const double Gp[5] = {0.1, 0.2, 0.2, 0.2, 0.3};
    int Gnx[5];
    int used = 0;
    for (int i = 0; i < 4; ++i) {
        Gnx[i] = static_cast<int>(std::ceil(Gp[i] * double(nx)));
        used += Gnx[i];
    }
    Gnx[4] = nx - used;

    const int off0 = 0;
    const int off1 = Gnx[0];
    const int off2 = Gnx[0] + Gnx[1];
    const int off3 = Gnx[0] + Gnx[1] + Gnx[2];
    const int off4 = Gnx[0] + Gnx[1] + Gnx[2] + Gnx[3];

    const double f0 = katsuura_sub(shuffled, off0, Gnx[0]);
    const double f1 = ackley_sub(shuffled, off1, Gnx[1]);
    const double f2 = grie_rosen_sub(shuffled, off2, Gnx[2]);
    const double f3 = schwefel_sub(shuffled, off3, Gnx[3]);
    const double f4 = rastrigin_sub(shuffled, off4, Gnx[4]);
    return f0 + f1 + f2 + f3 + f4;
}

