void CEC2022SchafferF7::init(int dim)
{
    if (!(dim == 2 || dim == 10 || dim == 20)) {
        throw std::invalid_argument("CEC2022SchafferF7 supports only D = 2, 10, or 20.");
    }

    Problem::init(dim);

    Vec lo(dim, -100.0), hi(dim, 100.0);
    setBounds(lo, hi);

    load_embedded_data(dim);
}

void CEC2022SchafferF7::load_embedded_data(int dim)
{
    const double* shift_ptr = shift_data_for_dim(dim);
    const double* rot_ptr   = rotation_data_for_dim(dim);

    if (!shift_ptr || !rot_ptr) {
        throw std::runtime_error("Embedded CEC2022SchafferF7 data are unavailable for the requested dimension.");
    }

    shift_.assign(shift_ptr, shift_ptr + dim);
    rotation_.assign(rot_ptr, rot_ptr + dim * dim);
}

double CEC2022SchafferF7::evaluate_core(const Vec& x)
{
    const int D = dimension();

    Vec y(D, 0.0);
    for (int i = 0; i < D; ++i) {
        const double xi = x[i] - shift_[i];
        for (int r = 0; r < D; ++r) {
            y[r] += rotation_[r * D + i] * xi;
        }
    }

    double sum = 0.0;
    for (int i = 0; i < D - 1; ++i) {
        const double s = std::sqrt(y[i] * y[i] + y[i + 1] * y[i + 1]);
        const double root_s = std::sqrt(s);
        const double angle = 50.0 * std::pow(s, 0.2);
        const double sin_term = std::sin(angle);
        sum += root_s * (1.0 + sin_term * sin_term);
    }

    const double norm = static_cast<double>(D - 1);
    return (sum * sum) / (norm * norm) + 600.0;
}

void CEC2022SchafferF7::gradient_core(const Vec& x, Vec& g)
{
    const int D = dimension();
    g.assign(D, 0.0);

    Vec y(D, 0.0);
    for (int i = 0; i < D; ++i) {
        const double xi = x[i] - shift_[i];
        for (int r = 0; r < D; ++r) {
            y[r] += rotation_[r * D + i] * xi;
        }
    }

    const double eps = 1e-15;
    Vec pair_norm(D - 1, 0.0);
    Vec ds_dr(D - 1, 0.0);
    double sum = 0.0;

    for (int i = 0; i < D - 1; ++i) {
        const double r = std::sqrt(y[i] * y[i] + y[i + 1] * y[i + 1]);
        pair_norm[i] = r;

        if (r <= eps) {
            ds_dr[i] = 0.0;
            continue;
        }

        const double root_r = std::sqrt(r);
        const double angle = 50.0 * std::pow(r, 0.2);
        const double sin_a = std::sin(angle);
        const double cos_a = std::cos(angle);
        const double term = root_r * (1.0 + sin_a * sin_a);
        sum += term;

        ds_dr[i] = 0.5 * (1.0 + sin_a * sin_a) / root_r
                 + 20.0 * std::pow(r, -0.3) * sin_a * cos_a;
    }

    const double norm = static_cast<double>(D - 1);
    const double coeff = 2.0 * sum / (norm * norm);

    Vec grad_y(D, 0.0);
    for (int k = 0; k < D; ++k) {
        double gy = 0.0;
        if (k > 0 && pair_norm[k - 1] > eps) {
            gy += ds_dr[k - 1] * (y[k] / pair_norm[k - 1]);
        }
        if (k < D - 1 && pair_norm[k] > eps) {
            gy += ds_dr[k] * (y[k] / pair_norm[k]);
        }
        grad_y[k] = coeff * gy;
    }

    for (int j = 0; j < D; ++j) {
        double gx = 0.0;
        for (int r = 0; r < D; ++r) {
            gx += rotation_[r * D + j] * grad_y[r];
        }
        g[j] = gx;
    }
}

