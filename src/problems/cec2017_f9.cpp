constexpr double kPi = 3.1415926535897932384626433832795029;

inline void shiftfunc(const Vec& x, Vec& xshift, const double* Os, int nx) {
    xshift.resize(nx);
    for (int i = 0; i < nx; ++i) xshift[i] = x[i] - Os[i];
}

inline void rotatefunc(const Vec& x, Vec& xrot, const double* Mr, int nx) {
    xrot.assign(nx, 0.0);
    for (int i = 0; i < nx; ++i) {
        double acc = 0.0;
        for (int j = 0; j < nx; ++j) acc += x[j] * Mr[i * nx + j];
        xrot[i] = acc;
    }
}

inline void sr_func(const Vec& x, Vec& sr_x, int nx, const double* Os, const double* Mr,
                    double sh_rate, bool s_flag, bool r_flag) {
    Vec y(nx, 0.0);
    if (s_flag) {
        if (r_flag) {
            shiftfunc(x, y, Os, nx);
            for (int i = 0; i < nx; ++i) y[i] *= sh_rate;
            rotatefunc(y, sr_x, Mr, nx);
        } else {
            shiftfunc(x, sr_x, Os, nx);
            for (int i = 0; i < nx; ++i) sr_x[i] *= sh_rate;
        }
    } else {
        if (r_flag) {
            for (int i = 0; i < nx; ++i) y[i] = x[i] * sh_rate;
            rotatefunc(y, sr_x, Mr, nx);
        } else {
            sr_x.resize(nx);
            for (int i = 0; i < nx; ++i) sr_x[i] = x[i] * sh_rate;
        }
    }
}

// Levy, per the official reference (sh_rate = 1.0). NOTE the sin(pi*w_i + 1)
// term -- literally "+1" added to the angle, matching the official code
// (see the class-level comment in cec2017_f9.h).
inline double levy_func(const Vec& x, int nx, const double* Os, const double* Mr,
                        bool s_flag, bool r_flag) {
    Vec z;
    sr_func(x, z, nx, Os, Mr, 1.0, s_flag, r_flag);

    Vec w(nx);
    for (int i = 0; i < nx; ++i) w[i] = 1.0 + (z[i] - 1.0) / 4.0;

    const double term1 = std::sin(kPi * w[0]) * std::sin(kPi * w[0]);
    const double sinLast = std::sin(2.0 * kPi * w[nx - 1]);
    const double term3 = (w[nx - 1] - 1.0) * (w[nx - 1] - 1.0) * (1.0 + sinLast * sinLast);

    double sum = 0.0;
    for (int i = 0; i < nx - 1; ++i) {
        const double wi = w[i];
        const double s = std::sin(kPi * wi + 1.0);
        sum += (wi - 1.0) * (wi - 1.0) * (1.0 + 10.0 * s * s);
    }
    return term1 + sum + term3;
}

