void CEC2017F29::init(int dim) {
    if (!(dim == 10 || dim == 30 || dim == 50)) {
        throw std::invalid_argument("CEC2017F29 supports only dimensions 10, 30, and 50.");
    }
    Problem::init(dim);
    Vec lo(dim, -100.0), hi(dim, 100.0);
    setBounds(lo, hi);
    load_embedded_data(dim);

    Vec xopt(shift_.begin(), shift_.begin() + dim);
    setKnownGlobalOptimum(2900.0, xopt);
}

void CEC2017F29::load_embedded_data(int dim) {
    const double* s = shift_data_for_dim(dim);
    const double* r = rotation_data_for_dim(dim);
    const int* sh = shuffle_data_for_dim(dim);
    if (!s || !r || !sh) {
        throw std::runtime_error("Missing embedded CEC2017 F29 data.");
    }
    shift_.assign(s, s + 3 * dim);
    rotation_.assign(r, r + 3 * dim * dim);
    shuffle_.assign(sh, sh + 3 * dim);
}

double CEC2017F29::evaluate_core(const Vec& x) {
    const int D = dimension();
    if (static_cast<int>(x.size()) != D) {
        throw std::invalid_argument("CEC2017F29::evaluate_core received vector with wrong dimension.");
    }

    const int cf_num = 3;
    const double delta[3] = {10.0, 30.0, 50.0};
    const double bias[3]  = {0.0, 100.0, 200.0};
    double fit[3];

    fit[0] = hf05_component(x, D, shift_.data() + 0 * D, rotation_.data() + 0 * D * D, shuffle_.data() + 0 * D);
    fit[1] = hf06_component(x, D, shift_.data() + 1 * D, rotation_.data() + 1 * D * D, shuffle_.data() + 1 * D);
    fit[2] = hf07_component(x, D, shift_.data() + 2 * D, rotation_.data() + 2 * D * D, shuffle_.data() + 2 * D);

    const double f = cf_cal(x, D, shift_.data(), delta, bias, fit, cf_num) + 2900.0;
    return std::isfinite(f) ? f : 1e12;
}

void CEC2017F29::gradient_core(const Vec& x, Vec& g) {
    const int D = dimension();
    g.assign(D, 0.0);
    const double eps = 1.0e-6;
    Vec xp = x, xm = x;
    for (int i = 0; i < D; ++i) {
        xp[i] = x[i] + eps;
        xm[i] = x[i] - eps;
        const double fp = evaluate_core(xp);
        const double fm = evaluate_core(xm);
        g[i] = (fp - fm) / (2.0 * eps);
        xp[i] = x[i];
        xm[i] = x[i];
    }
}

