constexpr double kPi  = 3.1415926535897932384626433832795029;
constexpr double kE   = 2.7182818284590452353602874713526625;
constexpr double kInf = 1.0e99;

inline void shiftfunc(const Vec& x, Vec& xshift, const double* Os, int nx) {
    xshift.resize(nx);
    for (int i = 0; i < nx; ++i) xshift[i] = x[i] - Os[i];
}

inline void rotatefunc(const Vec& x, Vec& xrot, const double* Mr, int nx) {
    xrot.assign(nx, 0.0);
    for (int i = 0; i < nx; ++i) {
        double acc = 0.0;
        for (int j = 0; j < nx; ++j) acc += x[j] * Mr[i * nx + j];
        xrot[i] = acc;
    }
}

// ---- Hybrid sub-function building blocks (verbatim from F15/F16/F17) ----

inline double bent_cigar_sub(const Vec& y, int off, int n) {
    double f = y[off] * y[off];
    for (int i = 1; i < n; ++i) f += 1.0e6 * y[off + i] * y[off + i];
    return f;
}

inline double hgbat_sub(const Vec& y, int off, int n) {
    double r2 = 0.0, sumz = 0.0;
    for (int i = 0; i < n; ++i) {
        const double zi = y[off + i] * (5.0 / 100.0) - 1.0;
        r2 += zi * zi;
        sumz += zi;
    }
    const double alpha = 0.25;
    return std::pow(std::fabs(r2 * r2 - sumz * sumz), 2.0 * alpha) + (0.5 * r2 + sumz) / double(n) + 0.5;
}

inline double rastrigin_sub(const Vec& y, int off, int n) {
    double f = 0.0;
    for (int i = 0; i < n; ++i) {
        const double zi = y[off + i] * (5.12 / 100.0);
        f += zi * zi - 10.0 * std::cos(2.0 * kPi * zi) + 10.0;
    }
    return f;
}

inline double rosenbrock_sub(const Vec& y, int off, int n) {
    if (n == 0) return 0.0;
    Vec z(n);
    for (int i = 0; i < n; ++i) z[i] = y[off + i] * (2.048 / 100.0);
    z[0] += 1.0;
    double f = 0.0;
    for (int i = 0; i < n - 1; ++i) {
        z[i + 1] += 1.0;
        const double tmp1 = z[i] * z[i] - z[i + 1];
        const double tmp2 = z[i] - 1.0;
        f += 100.0 * tmp1 * tmp1 + tmp2 * tmp2;
    }
    return f;
}

inline double escaffer6_sub(const Vec& y, int off, int n) {
    double f = 0.0;
    for (int i = 0; i < n - 1; ++i) {
        const double a = y[off + i], b = y[off + i + 1];
        const double s = std::sin(std::sqrt(a * a + b * b));
        const double t1 = s * s;
        const double t2 = 1.0 + 0.001 * (a * a + b * b);
        f += 0.5 + (t1 - 0.5) / (t2 * t2);
    }
    const double a = y[off + n - 1], b = y[off];
    const double s = std::sin(std::sqrt(a * a + b * b));
    const double t1 = s * s;
    const double t2 = 1.0 + 0.001 * (a * a + b * b);
    f += 0.5 + (t1 - 0.5) / (t2 * t2);
    return f;
}

inline double schwefel_sub(const Vec& y, int off, int n) {
    double f = 0.0;
    for (int i = 0; i < n; ++i) {
        double zi = y[off + i] * (1000.0 / 100.0) + 4.209687462275036e+002;
        if (zi > 500.0) {
            const double r = 500.0 - std::fmod(zi, 500.0);
            f -= r * std::sin(std::sqrt(r));
            const double tmp = (zi - 500.0) / 100.0;
            f += tmp * tmp / double(n);
        } else if (zi < -500.0) {
            const double r = 500.0 - std::fmod(std::fabs(zi), 500.0);
            f -= (-500.0 + std::fmod(std::fabs(zi), 500.0)) * std::sin(std::sqrt(r));
            const double tmp = (zi + 500.0) / 100.0;
            f += tmp * tmp / double(n);
        } else {
            f -= zi * std::sin(std::sqrt(std::fabs(zi)));
        }
    }
    f += 4.189828872724338e+002 * double(n);
    return f;
}

inline double katsuura_sub(const Vec& y, int off, int n) {
    double f = 1.0;
    const double tmp3 = std::pow(double(n), 1.2);
    for (int i = 0; i < n; ++i) {
        const double zi = y[off + i] * (5.0 / 100.0);
        double temp = 0.0;
        for (int j = 1; j <= 32; ++j) {
            const double t1 = std::pow(2.0, double(j));
            const double t2 = t1 * zi;
            temp += std::fabs(t2 - std::floor(t2 + 0.5)) / t1;
        }
        f *= std::pow(1.0 + double(i + 1) * temp, 10.0 / tmp3);
    }
    const double tmp1 = 10.0 / double(n) / double(n);
    return f * tmp1 - tmp1;
}

inline double ackley_sub(const Vec& y, int off, int n) {
    double sum1 = 0.0, sum2 = 0.0;
    for (int i = 0; i < n; ++i) {
        const double zi = y[off + i];
        sum1 += zi * zi;
        sum2 += std::cos(2.0 * kPi * zi);
    }
    sum1 = -0.2 * std::sqrt(sum1 / double(n));
    sum2 /= double(n);
    return kE - 20.0 * std::exp(sum1) - std::exp(sum2) + 20.0;
}

inline double grie_rosen_sub(const Vec& y, int off, int n) {
    if (n == 0) return 0.0;
    Vec z(n);
    for (int i = 0; i < n; ++i) z[i] = y[off + i] * (5.0 / 100.0);
    z[0] += 1.0;
    double f = 0.0;
    for (int i = 0; i < n - 1; ++i) {
        z[i + 1] += 1.0;
        const double tmp1 = z[i] * z[i] - z[i + 1];
        const double tmp2 = z[i] - 1.0;
        const double temp = 100.0 * tmp1 * tmp1 + tmp2 * tmp2;
        f += temp * temp / 4000.0 - std::cos(temp) + 1.0;
    }
    const double tmp1 = z[n - 1] * z[n - 1] - z[0];
    const double tmp2 = z[n - 1] - 1.0;
    const double temp = 100.0 * tmp1 * tmp1 + tmp2 * tmp2;
    f += temp * temp / 4000.0 - std::cos(temp) + 1.0;
    return f;
}

// ---- Whole-hybrid components: shift + rotate + shuffle, then group+sum ----

inline double hf05_component(const Vec& x, int nx, const double* Os, const double* Mr, const int* S) {
    Vec y; shiftfunc(x, y, Os, nx);
    Vec z; rotatefunc(y, z, Mr, nx);
    Vec shuffled(nx);
    for (int i = 0; i < nx; ++i) shuffled[i] = z[S[i] - 1];
    const double Gp[4] = {0.2, 0.2, 0.3, 0.3};
    int Gnx[4], used = 0;
    for (int i = 0; i < 3; ++i) { Gnx[i] = static_cast<int>(std::ceil(Gp[i] * double(nx))); used += Gnx[i]; }
    Gnx[3] = nx - used;
    const int off0 = 0, off1 = Gnx[0], off2 = Gnx[0] + Gnx[1], off3 = Gnx[0] + Gnx[1] + Gnx[2];
    return bent_cigar_sub(shuffled, off0, Gnx[0]) + hgbat_sub(shuffled, off1, Gnx[1])
         + rastrigin_sub(shuffled, off2, Gnx[2]) + rosenbrock_sub(shuffled, off3, Gnx[3]);
}

inline double hf06_component(const Vec& x, int nx, const double* Os, const double* Mr, const int* S) {
    Vec y; shiftfunc(x, y, Os, nx);
    Vec z; rotatefunc(y, z, Mr, nx);
    Vec shuffled(nx);
    for (int i = 0; i < nx; ++i) shuffled[i] = z[S[i] - 1];
    const double Gp[4] = {0.2, 0.2, 0.3, 0.3};
    int Gnx[4], used = 0;
    for (int i = 0; i < 3; ++i) { Gnx[i] = static_cast<int>(std::ceil(Gp[i] * double(nx))); used += Gnx[i]; }
    Gnx[3] = nx - used;
    const int off0 = 0, off1 = Gnx[0], off2 = Gnx[0] + Gnx[1], off3 = Gnx[0] + Gnx[1] + Gnx[2];
    return escaffer6_sub(shuffled, off0, Gnx[0]) + hgbat_sub(shuffled, off1, Gnx[1])
         + rosenbrock_sub(shuffled, off2, Gnx[2]) + schwefel_sub(shuffled, off3, Gnx[3]);
}

inline double hf07_component(const Vec& x, int nx, const double* Os, const double* Mr, const int* S) {
    Vec y; shiftfunc(x, y, Os, nx);
    Vec z; rotatefunc(y, z, Mr, nx);
    Vec shuffled(nx);
    for (int i = 0; i < nx; ++i) shuffled[i] = z[S[i] - 1];
    const double Gp[5] = {0.1, 0.2, 0.2, 0.2, 0.3};
    int Gnx[5], used = 0;
    for (int i = 0; i < 4; ++i) { Gnx[i] = static_cast<int>(std::ceil(Gp[i] * double(nx))); used += Gnx[i]; }
    Gnx[4] = nx - used;
    const int off0 = 0, off1 = Gnx[0], off2 = Gnx[0] + Gnx[1];
    const int off3 = Gnx[0] + Gnx[1] + Gnx[2], off4 = Gnx[0] + Gnx[1] + Gnx[2] + Gnx[3];
    return katsuura_sub(shuffled, off0, Gnx[0]) + ackley_sub(shuffled, off1, Gnx[1])
         + grie_rosen_sub(shuffled, off2, Gnx[2]) + schwefel_sub(shuffled, off3, Gnx[3])
         + rastrigin_sub(shuffled, off4, Gnx[4]);
}

inline double cf_cal(const Vec& x, int nx, const double* Os, const double* delta,
                     const double* bias, double* fit, int cf_num) {
    std::vector<double> w(cf_num, 0.0);
    double w_max = 0.0, w_sum = 0.0;
    for (int i = 0; i < cf_num; ++i) {
        fit[i] += bias[i];
        double dist2 = 0.0;
        for (int j = 0; j < nx; ++j) {
            const double d = x[j] - Os[i * nx + j];
            dist2 += d * d;
        }
        if (dist2 != 0.0) {
            w[i] = std::pow(1.0 / dist2, 0.5) * std::exp(-dist2 / (2.0 * nx * delta[i] * delta[i]));
        } else {
            w[i] = kInf;
        }
        if (w[i] > w_max) w_max = w[i];
        w_sum += w[i];
    }
    if (w_max == 0.0) {
        std::fill(w.begin(), w.end(), 1.0);
        w_sum = double(cf_num);
    }
    double f = 0.0;
    for (int i = 0; i < cf_num; ++i) f += (w[i] / w_sum) * fit[i];
    return f;
}

