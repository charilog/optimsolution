inline void shiftfunc(const Vec& x, Vec& xshift, const double* Os, int nx) {
    xshift.resize(nx);
    for (int i = 0; i < nx; ++i) xshift[i] = x[i] - Os[i];
}

inline void rotatefunc(const Vec& x, Vec& xrot, const double* Mr, int nx) {
    xrot.assign(nx, 0.0);
    for (int i = 0; i < nx; ++i) {
        double acc = 0.0;
        for (int j = 0; j < nx; ++j) acc += x[j] * Mr[i * nx + j];
        xrot[i] = acc;
    }
}

inline void sr_func(const Vec& x, Vec& sr_x, int nx, const double* Os, const double* Mr,
                    double sh_rate, bool s_flag, bool r_flag) {
    Vec y(nx, 0.0);
    if (s_flag) {
        if (r_flag) {
            shiftfunc(x, y, Os, nx);
            for (int i = 0; i < nx; ++i) y[i] *= sh_rate;
            rotatefunc(y, sr_x, Mr, nx);
        } else {
            shiftfunc(x, sr_x, Os, nx);
            for (int i = 0; i < nx; ++i) sr_x[i] *= sh_rate;
        }
    } else {
        if (r_flag) {
            for (int i = 0; i < nx; ++i) y[i] = x[i] * sh_rate;
            rotatefunc(y, sr_x, Mr, nx);
        } else {
            sr_x.resize(nx);
            for (int i = 0; i < nx; ++i) sr_x[i] = x[i] * sh_rate;
        }
    }
}

inline double ellips_func(const Vec& x, int nx, const double* Os, const double* Mr,
                          bool s_flag, bool r_flag) {
    Vec z;
    sr_func(x, z, nx, Os, Mr, 1.0, s_flag, r_flag);
    double f = 0.0;
    if (nx == 1) return z[0] * z[0];
    for (int i = 0; i < nx; ++i) {
        f += std::pow(10.0, 6.0 * i / (nx - 1.0)) * z[i] * z[i];
    }
    return f;
}

inline double bent_cigar_func(const Vec& x, int nx, const double* Os, const double* Mr,
                              bool s_flag, bool r_flag) {
    Vec z;
    sr_func(x, z, nx, Os, Mr, 1.0, s_flag, r_flag);
    double f = z[0] * z[0];
    for (int i = 1; i < nx; ++i) f += 1.0e6 * z[i] * z[i];
    return f;
}

inline double discus_func(const Vec& x, int nx, const double* Os, const double* Mr,
                          bool s_flag, bool r_flag) {
    Vec z;
    sr_func(x, z, nx, Os, Mr, 1.0, s_flag, r_flag);
    double f = 1.0e6 * z[0] * z[0];
    for (int i = 1; i < nx; ++i) f += z[i] * z[i];
    return f;
}

inline double rosenbrock_func(const Vec& x, int nx, const double* Os, const double* Mr,
                              bool s_flag, bool r_flag) {
    Vec z;
    sr_func(x, z, nx, Os, Mr, 2.048 / 100.0, s_flag, r_flag);
    if (nx == 0) return 0.0;
    z[0] += 1.0;
    double f = 0.0;
    for (int i = 0; i < nx - 1; ++i) {
        z[i + 1] += 1.0;
        const double tmp1 = z[i] * z[i] - z[i + 1];
        const double tmp2 = z[i] - 1.0;
        f += 100.0 * tmp1 * tmp1 + tmp2 * tmp2;
    }
    return f;
}

inline double cf_cal(const Vec& x, int nx, const double* Os, const double* delta,
                     const double* bias, double* fit, int cf_num) {
    std::vector<double> w(cf_num, 0.0);
    double w_max = 0.0;
    double w_sum = 0.0;

    for (int i = 0; i < cf_num; ++i) {
        fit[i] += bias[i];
        double dist2 = 0.0;
        for (int j = 0; j < nx; ++j) {
            const double d = x[j] - Os[i * nx + j];
            dist2 += d * d;
        }
        if (dist2 != 0.0) {
            w[i] = std::pow(1.0 / dist2, 0.5) *
                   std::exp(-dist2 / (2.0 * nx * delta[i] * delta[i]));
        } else {
            w[i] = kInf;
        }
        if (w[i] > w_max) w_max = w[i];
        w_sum += w[i];
    }

    if (w_max == 0.0) {
        std::fill(w.begin(), w.end(), 1.0);
        w_sum = static_cast<double>(cf_num);
    }

    double f = 0.0;
    for (int i = 0; i < cf_num; ++i) f += (w[i] / w_sum) * fit[i];
    return f;
}

