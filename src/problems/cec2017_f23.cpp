void CEC2017F23::init(int dim) {
    if (!(dim == 10 || dim == 30 || dim == 50)) {
        throw std::invalid_argument("CEC2017F23 supports only dimensions 10, 30, and 50.");
    }
    Problem::init(dim);
    Vec lo(dim, -100.0), hi(dim, 100.0);
    setBounds(lo, hi);
    load_embedded_data(dim);

    Vec xopt(shift_.begin(), shift_.begin() + dim);
    setKnownGlobalOptimum(2300.0, xopt);
}

void CEC2017F23::load_embedded_data(int dim) {
    const double* s = shift_data_for_dim(dim);
    const double* r = rotation_data_for_dim(dim);
    if (!s || !r) {
        throw std::runtime_error("Missing embedded CEC2017 F23 data.");
    }
    shift_.assign(s, s + 4 * dim);
    rotation_.assign(r, r + 4 * dim * dim);
}

double CEC2017F23::evaluate_core(const Vec& x) {
    const int D = dimension();
    if (static_cast<int>(x.size()) != D) {
        throw std::invalid_argument("CEC2017F23::evaluate_core received vector with wrong dimension.");
    }

    const int cf_num = 4;
    const double delta[4] = {10.0, 20.0, 30.0, 40.0};
    const double bias[4]  = {0.0, 100.0, 200.0, 300.0};
    double fit[4] = {0.0, 0.0, 0.0, 0.0};

    for (int i = 0; i < cf_num; ++i) {
        const double* Os = shift_.data() + i * D;
        const double* Mr = rotation_.data() + i * D * D;
        Vec z;
        switch (i) {
        case 0:
            sr_func(x, z, D, Os, Mr, 2.048 / 100.0);
            fit[i] = rosenbrock_raw(z);
            break;
        case 1:
            sr_func(x, z, D, Os, Mr, 1.0);
            fit[i] = 1000.0 * ackley_raw(z) / 100.0;
            break;
        case 2:
            sr_func(x, z, D, Os, Mr, 1000.0 / 100.0);
            fit[i] = schwefel_raw(z);
            break;
        case 3:
            sr_func(x, z, D, Os, Mr, 5.12 / 100.0);
            fit[i] = rastrigin_raw(z);
            break;
        }
    }

    const double f = cf_cal(x, D, shift_.data(), delta, bias, fit, cf_num) + 2300.0;
    return std::isfinite(f) ? f : 1e12;
}

void CEC2017F23::gradient_core(const Vec& x, Vec& g) {
    const int D = dimension();
    g.assign(D, 0.0);
    const double eps = 1.0e-6;
    Vec xp = x, xm = x;
    for (int i = 0; i < D; ++i) {
        xp[i] = x[i] + eps;
        xm[i] = x[i] - eps;
        const double fp = evaluate_core(xp);
        const double fm = evaluate_core(xm);
        g[i] = (fp - fm) / (2.0 * eps);
        xp[i] = x[i];
        xm[i] = x[i];
    }
}

