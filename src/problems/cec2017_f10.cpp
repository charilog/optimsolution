inline void shiftfunc(const Vec& x, Vec& xshift, const double* Os, int nx) {
    xshift.resize(nx);
    for (int i = 0; i < nx; ++i) xshift[i] = x[i] - Os[i];
}

inline void rotatefunc(const Vec& x, Vec& xrot, const double* Mr, int nx) {
    xrot.assign(nx, 0.0);
    for (int i = 0; i < nx; ++i) {
        double acc = 0.0;
        for (int j = 0; j < nx; ++j) acc += x[j] * Mr[i * nx + j];
        xrot[i] = acc;
    }
}

inline void sr_func(const Vec& x, Vec& sr_x, int nx, const double* Os, const double* Mr,
                    double sh_rate, bool s_flag, bool r_flag) {
    Vec y(nx, 0.0);
    if (s_flag) {
        if (r_flag) {
            shiftfunc(x, y, Os, nx);
            for (int i = 0; i < nx; ++i) y[i] *= sh_rate;
            rotatefunc(y, sr_x, Mr, nx);
        } else {
            shiftfunc(x, sr_x, Os, nx);
            for (int i = 0; i < nx; ++i) sr_x[i] *= sh_rate;
        }
    } else {
        if (r_flag) {
            for (int i = 0; i < nx; ++i) y[i] = x[i] * sh_rate;
            rotatefunc(y, sr_x, Mr, nx);
        } else {
            sr_x.resize(nx);
            for (int i = 0; i < nx; ++i) sr_x[i] = x[i] * sh_rate;
        }
    }
}

// Schwefel, per the official reference (sh_rate = 1000/100 = 10).
inline double schwefel_func(const Vec& x, int nx, const double* Os, const double* Mr,
                            bool s_flag, bool r_flag) {
    Vec z;
    sr_func(x, z, nx, Os, Mr, 1000.0 / 100.0, s_flag, r_flag);

    double f = 0.0;
    for (int i = 0; i < nx; ++i) {
        double zi = z[i] + 4.209687462275036e+002;
        if (zi > 500.0) {
            const double r = 500.0 - std::fmod(zi, 500.0);
            f -= r * std::sin(std::sqrt(r));
            const double tmp = (zi - 500.0) / 100.0;
            f += tmp * tmp / double(nx);
        } else if (zi < -500.0) {
            const double r = 500.0 - std::fmod(std::fabs(zi), 500.0);
            f -= (-500.0 + std::fmod(std::fabs(zi), 500.0)) * std::sin(std::sqrt(r));
            const double tmp = (zi + 500.0) / 100.0;
            f += tmp * tmp / double(nx);
        } else {
            f -= zi * std::sin(std::sqrt(std::fabs(zi)));
        }
    }
    f += 4.189828872724338e+002 * double(nx);
    return f;
}

