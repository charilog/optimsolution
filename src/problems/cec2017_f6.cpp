inline void shiftfunc(const Vec& x, Vec& xshift, const double* Os, int nx) {
    xshift.resize(nx);
    for (int i = 0; i < nx; ++i) xshift[i] = x[i] - Os[i];
}

// schaffer_F7, per the official reference. NOTE: intentionally uses the
// shift-only vector (see the class-level comment in cec2017_f6.h) -- the
// rotation matrix is deliberately NOT applied here, to stay numerically
// identical to the official/published results.
inline double schaffer_f7_func(const Vec& x, int nx, const double* Os) {
    Vec y;
    shiftfunc(x, y, Os, nx);
    double f = 0.0;
    for (int i = 0; i < nx - 1; ++i) {
        const double w = std::sqrt(y[i] * y[i] + y[i + 1] * y[i + 1]);
        const double tmp = std::sin(50.0 * std::pow(w, 0.2));
        f += std::sqrt(w) + std::sqrt(w) * tmp * tmp;
    }
    const double denom = double(nx - 1);
    return f * f / (denom * denom);
}

