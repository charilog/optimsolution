constexpr double kPi = 3.1415926535897932384626433832795029;
constexpr double kE  = 2.7182818284590452353602874713526625;

inline void shiftfunc(const Vec& x, Vec& xshift, const double* Os, int nx) {
    xshift.resize(nx);
    for (int i = 0; i < nx; ++i) xshift[i] = x[i] - Os[i];
}

inline void rotatefunc(const Vec& x, Vec& xrot, const double* Mr, int nx) {
    xrot.assign(nx, 0.0);
    for (int i = 0; i < nx; ++i) {
        double acc = 0.0;
        for (int j = 0; j < nx; ++j) acc += x[j] * Mr[i * nx + j];
        xrot[i] = acc;
    }
}

inline double hgbat_sub(const Vec& y, int off, int n) {
    Vec z(n);
    double r2 = 0.0, sumz = 0.0;
    for (int i = 0; i < n; ++i) {
        const double zi = y[off + i] * (5.0 / 100.0) - 1.0;
        z[i] = zi;
        r2 += zi * zi;
        sumz += zi;
    }
    const double alpha = 0.25;
    return std::pow(std::fabs(r2 * r2 - sumz * sumz), 2.0 * alpha) + (0.5 * r2 + sumz) / double(n) + 0.5;
}

inline double katsuura_sub(const Vec& y, int off, int n) {
    double f = 1.0;
    const double tmp3 = std::pow(double(n), 1.2);
    for (int i = 0; i < n; ++i) {
        const double zi = y[off + i] * (5.0 / 100.0);
        double temp = 0.0;
        for (int j = 1; j <= 32; ++j) {
            const double t1 = std::pow(2.0, double(j));
            const double t2 = t1 * zi;
            temp += std::fabs(t2 - std::floor(t2 + 0.5)) / t1;
        }
        f *= std::pow(1.0 + double(i + 1) * temp, 10.0 / tmp3);
    }
    const double tmp1 = 10.0 / double(n) / double(n);
    return f * tmp1 - tmp1;
}

inline double ackley_sub(const Vec& y, int off, int n) {
    double sum1 = 0.0, sum2 = 0.0;
    for (int i = 0; i < n; ++i) {
        const double zi = y[off + i];
        sum1 += zi * zi;
        sum2 += std::cos(2.0 * kPi * zi);
    }
    sum1 = -0.2 * std::sqrt(sum1 / double(n));
    sum2 /= double(n);
    return kE - 20.0 * std::exp(sum1) - std::exp(sum2) + 20.0;
}

inline double rastrigin_sub(const Vec& y, int off, int n) {
    double f = 0.0;
    for (int i = 0; i < n; ++i) {
        const double zi = y[off + i] * (5.12 / 100.0);
        f += zi * zi - 10.0 * std::cos(2.0 * kPi * zi) + 10.0;
    }
    return f;
}

inline double schwefel_sub(const Vec& y, int off, int n) {
    double f = 0.0;
    for (int i = 0; i < n; ++i) {
        double zi = y[off + i] * (1000.0 / 100.0) + 4.209687462275036e+002;
        if (zi > 500.0) {
            const double r = 500.0 - std::fmod(zi, 500.0);
            f -= r * std::sin(std::sqrt(r));
            const double tmp = (zi - 500.0) / 100.0;
            f += tmp * tmp / double(n);
        } else if (zi < -500.0) {
            const double r = 500.0 - std::fmod(std::fabs(zi), 500.0);
            f -= (-500.0 + std::fmod(std::fabs(zi), 500.0)) * std::sin(std::sqrt(r));
            const double tmp = (zi + 500.0) / 100.0;
            f += tmp * tmp / double(n);
        } else {
            f -= zi * std::sin(std::sqrt(std::fabs(zi)));
        }
    }
    f += 4.189828872724338e+002 * double(n);
    return f;
}

// Expanded Scaffer's F6, QUIRKY variant -- this is the reference code's
// `schaffer_F7_func` (the SAME function/quirk as the standalone F6, see
// cec2017_f6.h and cec2017_f20.h class comments), used here for group 6
// (the LAST group). It reads the FIRST n elements of the WHOLE shuffled
// vector, NOT this group's own slice.
inline double schaffer_f7_sub_quirky(const Vec& yFull, int n) {
    double f = 0.0;
    for (int i = 0; i < n - 1; ++i) {
        const double w = std::sqrt(yFull[i] * yFull[i] + yFull[i + 1] * yFull[i + 1]);
        const double tmp = std::sin(50.0 * std::pow(w, 0.2));
        f += std::sqrt(w) + std::sqrt(w) * tmp * tmp;
    }
    const double denom = double(n - 1);
    return f * f / (denom * denom);
}

// Hybrid Function 10, per the official reference: shift+rotate once,
// shuffle via the fixed permutation S, split into 6 groups (proportions
// 0.1/0.1/0.2/0.2/0.2/0.2 of D, last group takes the remainder), and sum
// HGBat + Katsuura + Ackley + Rastrigin + Schwefel + ScafferF6(quirky) over
// the six groups in turn.
inline double hf10_func(const Vec& x, int nx, const double* Os, const double* Mr,
                        const int* S) {
    Vec y;
    shiftfunc(x, y, Os, nx);
    Vec z;
    rotatefunc(y, z, Mr, nx);

    Vec shuffled(nx);
    for (int i = 0; i < nx; ++i) shuffled[i] = z[S[i] - 1];

    const double Gp[6] = {0.1, 0.1, 0.2, 0.2, 0.2, 0.2};
    int Gnx[6];
    int used = 0;
    for (int i = 0; i < 5; ++i) {
        Gnx[i] = static_cast<int>(std::ceil(Gp[i] * double(nx)));
        used += Gnx[i];
    }
    Gnx[5] = nx - used;

    const int off0 = 0;
    const int off1 = Gnx[0];
    const int off2 = Gnx[0] + Gnx[1];
    const int off3 = Gnx[0] + Gnx[1] + Gnx[2];
    const int off4 = Gnx[0] + Gnx[1] + Gnx[2] + Gnx[3];

    const double f0 = hgbat_sub(shuffled, off0, Gnx[0]);
    const double f1 = katsuura_sub(shuffled, off1, Gnx[1]);
    const double f2 = ackley_sub(shuffled, off2, Gnx[2]);
    const double f3 = rastrigin_sub(shuffled, off3, Gnx[3]);
    const double f4 = schwefel_sub(shuffled, off4, Gnx[4]);
    const double f5 = schaffer_f7_sub_quirky(shuffled, Gnx[5]); // quirk: reads shuffled[0..Gnx[5]-1]
    return f0 + f1 + f2 + f3 + f4 + f5;
}

