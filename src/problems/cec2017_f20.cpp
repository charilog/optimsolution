CEC2017F20::CEC2017F20() {
    setName("cec2017f20");
    setFullName("CEC 2017 F20 - Hybrid Function 10 (N=6)");
    setModality("multimodal");
    setSeparability("non-separable");
    setCategory("cec2017 hybrid benchmark");
}

void CEC2017F20::init(int dim) {
    if (!(dim == 10 || dim == 30 || dim == 50)) {
        throw std::invalid_argument("CEC2017F20 supports only dimensions 10, 30, and 50.");
    }
    Problem::init(dim);
    Vec lo(dim, -100.0), hi(dim, 100.0);
    setBounds(lo, hi);
    load_embedded_data(dim);
    setKnownGlobalOptimum(2000.0, shift_);
}

void CEC2017F20::load_embedded_data(int dim) {
    const double* s = shift_data_for_dim(dim);
    const double* r = rotation_data_for_dim(dim);
    const int* sh = shuffle_data_for_dim(dim);
    if (!s || !r || !sh) {
        throw std::runtime_error("Missing embedded CEC2017 F20 data.");
    }
    shift_.assign(s, s + dim);
    rotation_.assign(r, r + dim * dim);
    shuffle_.assign(sh, sh + dim);
}

double CEC2017F20::evaluate_core(const Vec& x) {
    const int D = dimension();
    if (static_cast<int>(x.size()) != D) {
        throw std::invalid_argument("CEC2017F20::evaluate_core received vector with wrong dimension.");
    }
    const double f = hf10_func(x, D, shift_.data(), rotation_.data(), shuffle_.data()) + 2000.0;
    return std::isfinite(f) ? f : 1e12;
}

void CEC2017F20::gradient_core(const Vec& x, Vec& g) {
    const int D = dimension();
    g.assign(D, 0.0);
    const double eps = 1.0e-6;
    Vec xp = x, xm = x;
    for (int i = 0; i < D; ++i) {
        xp[i] = x[i] + eps;
        xm[i] = x[i] - eps;
        const double fp = evaluate_core(xp);
        const double fm = evaluate_core(xm);
        g[i] = (fp - fm) / (2.0 * eps);
        xp[i] = x[i];
        xm[i] = x[i];
    }
}

