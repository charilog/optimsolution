inline void shiftfunc(const Vec& x, Vec& xshift, const double* Os, int nx) {
    xshift.resize(nx);
    for (int i = 0; i < nx; ++i) xshift[i] = x[i] - Os[i];
}

inline void rotatefunc(const Vec& x, Vec& xrot, const double* Mr, int nx) {
    xrot.assign(nx, 0.0);
    for (int i = 0; i < nx; ++i) {
        double acc = 0.0;
        for (int j = 0; j < nx; ++j) acc += x[j] * Mr[i * nx + j];
        xrot[i] = acc;
    }
}

// Sub-function building blocks, unscaled/unshifted -- the single top-level
// shift+rotate (see hf02_func below) already happened once; each
// sub-function here only applies its own internal scale factor to its
// slice of the already-shifted+rotated+shuffled vector.

inline double ellips_sub(const Vec& y, int off, int n) {
    if (n == 1) return y[off] * y[off];
    double f = 0.0;
    for (int i = 0; i < n; ++i) {
        f += std::pow(10.0, 6.0 * i / double(n - 1)) * y[off + i] * y[off + i];
    }
    return f;
}

inline double schwefel_sub(const Vec& y, int off, int n) {
    double f = 0.0;
    for (int i = 0; i < n; ++i) {
        double zi = y[off + i] * (1000.0 / 100.0) + 4.209687462275036e+002;
        if (zi > 500.0) {
            const double r = 500.0 - std::fmod(zi, 500.0);
            f -= r * std::sin(std::sqrt(r));
            const double tmp = (zi - 500.0) / 100.0;
            f += tmp * tmp / double(n);
        } else if (zi < -500.0) {
            const double r = 500.0 - std::fmod(std::fabs(zi), 500.0);
            f -= (-500.0 + std::fmod(std::fabs(zi), 500.0)) * std::sin(std::sqrt(r));
            const double tmp = (zi + 500.0) / 100.0;
            f += tmp * tmp / double(n);
        } else {
            f -= zi * std::sin(std::sqrt(std::fabs(zi)));
        }
    }
    f += 4.189828872724338e+002 * double(n);
    return f;
}

inline double bent_cigar_sub(const Vec& y, int off, int n) {
    double f = y[off] * y[off];
    for (int i = 1; i < n; ++i) f += 1.0e6 * y[off + i] * y[off + i];
    return f;
}

// Hybrid Function 2, per the official reference: shift+rotate once, shuffle
// via the fixed permutation S, split into 3 groups (proportions 0.3/0.3/0.4
// of D, last group takes the remainder), and sum Ellip + Schwefel +
// BentCigar over the three groups in turn.
inline double hf02_func(const Vec& x, int nx, const double* Os, const double* Mr,
                        const int* S) {
    Vec y;
    shiftfunc(x, y, Os, nx);
    Vec z;
    rotatefunc(y, z, Mr, nx);

    Vec shuffled(nx);
    for (int i = 0; i < nx; ++i) shuffled[i] = z[S[i] - 1];

    const double Gp[3] = {0.3, 0.3, 0.4};
    int Gnx[3];
    int used = 0;
    for (int i = 0; i < 2; ++i) {
        Gnx[i] = static_cast<int>(std::ceil(Gp[i] * double(nx)));
        used += Gnx[i];
    }
    Gnx[2] = nx - used;

    const int off0 = 0;
    const int off1 = Gnx[0];
    const int off2 = Gnx[0] + Gnx[1];

    const double f0 = ellips_sub(shuffled, off0, Gnx[0]);
    const double f1 = schwefel_sub(shuffled, off1, Gnx[1]);
    const double f2 = bent_cigar_sub(shuffled, off2, Gnx[2]);
    return f0 + f1 + f2;
}

